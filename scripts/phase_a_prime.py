def _resolver_subcause(reason: str) -> str:
    """For ``upstream-not-invocable-here``, name the REAL sub-cause so
    the dev-env limitation is honestly attributed (NOT papered over as
    'no entrypoint exists'). Mirrors the resolver's own categories."""
    r = reason or ""
    m = re.search(r"No module named '([^']+)'", r)
    if m or "ModuleNotFoundError" in r:
        return f"missing-dep:{m.group(1)}" if m else "missing-dep:?"
    if "ImportError" in r and (
        "relative import" in r
        or "attempted relative" in r
        or "no known parent package" in r
        or "beyond top-level package" in r
    ):
        return "relative-import-packaging"
    if "AssertionError" in r:
        return "assertion/precondition"
    if "AttributeError" in r and "triton" in r.lower():
        return "triton-api-AttributeError"
    if "TypeError" in r:
        return "TypeError"
    if "AttributeError" in r:
        return "AttributeError"
    if "ImportError" in r:
        return "ImportError"
    return "other"


