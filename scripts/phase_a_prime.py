def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if getattr(args, "accept_stale_cache", False):
        # Translate the CLI flag into the env var the loader reads.
        # Set here, BEFORE any code path imports / triggers the loader.
        os.environ["PA_ACCEPT_STALE_CACHE"] = "1"
    if getattr(args, "require_smoke", False):
        # Translate to env var s2_verify_task reads at smoke pre-filter step.
        # Default is "skip smoke when CUDA is available"; this forces it on.
        os.environ["PA_REQUIRE_S2_SMOKE"] = "1"
    if not VLLM_ROOT.is_dir() or not SGLANG_ROOT.is_dir():
        print(
            f"warning: infer roots missing ({VLLM_ROOT} / {SGLANG_ROOT}); "
            "Class-A transitive closure will be partial",
            file=sys.stderr,
        )
    if args.classify:
        return cmd_classify(args)
    if args.verify:
        args.task = args.verify
        return cmd_verify(args)
    if args.rewrite is not None:
        if args.rewrite != "__ALL__":
            args.task = args.rewrite
        return cmd_rewrite(args)
    if getattr(args, "resolve_entrypoint", False):
        # Thin delegate: the resolver lives in its own module so the
        # oracle-consistency anchor + S2-smoke gate stay cohesive and
        # independently testable. Only meta.yaml: oracle.gpu_triton is
        # ever touched, and ONLY for an oracle-verified entrypoint.
        import importlib.util as _ilu

        _s = _ilu.spec_from_file_location(
            "resolve_upstream_entrypoints",
            _SCRIPTS_DIR / "resolve_upstream_entrypoints.py",
        )
        _m = _ilu.module_from_spec(_s)
        # Register BEFORE exec so the module's @dataclass can resolve
        # its own __module__ in sys.modules (delegate-path fix).
        sys.modules["resolve_upstream_entrypoints"] = _m
        _s.loader.exec_module(_m)
        _argv: list[str] = []
        if args.task:
            _argv += ["--task", args.task]
        if args.all:
            _argv.append("--all")
        if args.apply:
            _argv.append("--apply")
        return _m.main(_argv)
    if args.run:
        return cmd_run(args)
    build_parser().print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())
