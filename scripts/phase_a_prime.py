                    r.task_id, r.tier, "BLOCKED(shapes-incomplete)",
                    f"BLOCKED(shapes-incomplete): the upstream "
                    f"entrypoint RESOLVES but the task's shapes.yaml "
                    f"does NOT enumerate a required (no-default) "
                    f"parameter, so build_inputs never produces it. "
                    f"The by-name adapter refuses to silently "
                    f"skip+shift positional args (ISSUE 1 soundness "
