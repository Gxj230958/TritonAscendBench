        # Entrypoint resolves (meta points at a callable that EXISTS).
        #
        # MUST-FIX 1 (codex r2 [confirmed]): the hardened resolver
        # verdict is the SINGLE SOURCE OF TRUTH. meta.yaml's entrypoint
        # may have been written by a PRE-hardening ``--apply`` run; a
        # plain ``s2_verify_task`` here only runs the S2-smoke (it does
