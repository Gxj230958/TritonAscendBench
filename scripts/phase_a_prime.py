                    r.task_id, r.tier, "BLOCKED(smoke-fail)",
                    f"BLOCKED(smoke-fail): a candidate resolved + was "
                    f"oracle-consistent but the resolver's REAL "
                    f"S2-smoke genuinely mismatched for a "
                    f"severing/interpret reason (NOT an overclaimed "
                    f"UNRUN). {rv_reason}{cand_suffix}",
