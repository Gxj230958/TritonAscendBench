        res.status = "BLOCKED"
        res.audit_leaks = (
            list((g_s or {}).get("audit_leaks", []))
            + list((g_s or {}).get("runtime_leaks", []))
        )
        res.reason = f"S2-gpu: {g_why}"
        return res
