# ───────────────────────────────────────────────────────────────────────────
# Data model
# ───────────────────────────────────────────────────────────────────────────
@dataclass
class SymbolClass:
    """One external symbol and its assigned class + proof."""

    symbol: str            # e.g. "vllm.logger.init_logger"
    module: str            # e.g. "vllm.logger"
    name: str              # e.g. "init_logger"
    cls: str               # CLASS_*
    proof: str = ""        # justification string (required for B)
    is_seed: bool = False  # module-scope side-effect seed (never dropped)
    blocked_reason: str = ""


@dataclass
class TaskClassification:
    task_id: str
    tier: str = "T0"                       # T0..T3
    symbols: list[SymbolClass] = field(default_factory=list)
    blocked: bool = False
    blocked_candidate: bool = False
    blocked_reason: str = ""
    closure_size: int = 0
    cycle_detected: bool = False
    depth_exceeded: bool = False
    diagnostics: list[str] = field(default_factory=list)

    def by_class(self, cls: str) -> list[SymbolClass]:
        return [s for s in self.symbols if s.cls == cls]


# ───────────────────────────────────────────────────────────────────────────
# AST helpers
# ───────────────────────────────────────────────────────────────────────────
def _module_top(mod: str) -> str:
    return (mod or "").split(".")[0]


def _is_external_module(mod: str) -> bool:
    """True iff `mod` resolves to vllm/sglang (the only severable surface)."""
    top = _module_top(mod)
    return top in {"vllm", "sglang"}


def _classify_module_member(module: str, name: str) -> tuple[str, str]:
    """Classify a single (module, name) external symbol.

    Returns ``(class, proof)``. Default is Class A (unknown -> A).
    """
    full = f"{module}.{name}" if name else module

    # ── Class D: stable third-party (CLASS_D_PKGS = einops, numpy, zmq). ──
    if _module_top(module) in CLASS_D_PKGS:
        top = _module_top(module)
        return CLASS_D, f"{module} is a Class-D stable PyPI package ({top}); declared in pyproject.toml [project].dependencies"

    # ── B-rewrite-public: tl/triton re-export. ──────────────────────
    if name in _TRITON_REEXPORT_NAMES and module in _TRITON_REEXPORT_MODULES:
        if name in _TRITON_REEXPORT_NOT_INERT:
            return CLASS_A, ""
        return (
            CLASS_B_REWRITE_PUBLIC,
            f"{full} is a verbatim re-export of public `triton`/`triton.language`; "
            f"rewrite to `import triton` / `import triton.language as tl` (Class-D peer, NOT shimmed)",
        )
    # Re-export module members that GATE behaviour stay Class A.
    if name in _TRITON_REEXPORT_NOT_INERT and module in _TRITON_REEXPORT_MODULES:
        return CLASS_A, ""

    # ── Class S: env/device/file-driven semantic config. ────────────
    if module in _CLASS_S_MODULES:
        return (
            CLASS_S,
            f"{full} reads env/device/file-driven config selection "
            f"(VLLM_* / tuned-config) -- Class-S: pin resolved_value, NOT shim",
        )
    if any(m in name for m in _CLASS_S_MARKERS) or any(
        m in full for m in _CLASS_S_MARKERS
    ):
        return (
            CLASS_S,
            f"{full} matches env/device/file config-selection marker; Class-S pinned semantic config",
        )

    # ── Class C: optional accel fork. ───────────────────────────────
    if module in _CLASS_C_MODULES or _module_top(module) in {
        "deep_gemm",
        "flash_attn",
    }:
        return (
            CLASS_C,
            f"{full} is an optional accel path (deep_gemm/flash_attn/_custom_ops); "
            f"reference = triton fallback. If no reachable triton fallback ⇒ BLOCKED",
        )
    if any(m in full for m in _CLASS_C_MARKERS):
        return (
            CLASS_C,
            f"{full} matches optional-accel marker (torch.ops._C / cuda_arch>=80); "
            f"reference = triton fallback or BLOCKED",
        )

    # ── B-inert-shim: provably-inert logging sink. ──────────────────
    if name in _LOGGER_FACTORY_NAMES and (
        module in _LOGGER_MODULES or "logger" in module
    ):
        return (
            CLASS_B_INERT_SHIM,
            f"{full} is a pure logging-sink factory; replaced by a recorded "
            f"deterministic no-op logger (zero numeric/shape/dtype/schedule effect)",
        )

    # ── default: Class A (unknown -> A; never silently inert). ───────
    return (
        CLASS_A,
        "",
    )


def _classify_non_severable(module: str, name: str) -> tuple[str, str, bool]:
    """Classify an import whose top is NOT vllm/sglang.

    The plan invariant forbids silently dropping ANY symbol -- the old
    code did ``if not _is_external_module(mod): continue`` which
    silently discarded real third-party imports such as
    ``from einops import rearrange`` (L1_13:33), so ``einops`` got NO
    Class-D proof and was invisibly dropped.

    Returns ``(class, proof, is_blocked_candidate)``:
      * stdlib / __future__ / torch / triton -> ``CLASS_TORCH_TRITON``
        (handled, always-available, never severed -- explicit
        category, never silently ignored).
      * Class-D allowlisted stable PyPI (einops) -> ``CLASS_D`` + proof,
        declared in ``pyproject.toml [project].dependencies``.
      * anything else (an unknown non-vllm/sglang package we cannot
        prove stable+pinned) -> ``CLASS_D`` *candidate* but flagged as
        a BLOCKED-candidate so it surfaces (NEVER silently ignored;
        "doubtful -> A/BLOCKED", plan §3 Class-D).
    """
    full = f"{module}.{name}" if name else module
    top = _module_top(module)

    # `sys.stdlib_module_names` (Py 3.10+) is the authoritative set of
    # *all* stdlib top-level modules, including C-extension internals
    # like `_hashlib` / `_socket` that the hand-list missed. A stdlib
    # module is always-available and never severed.
    _stdlib = getattr(sys, "stdlib_module_names", frozenset())
    if (
        top in _STDLIB_TOPS
        or top in _stdlib
        or top in _TORCH_TRITON_TOPS
        or top in {"__future__"}
    ):
        return (
            CLASS_TORCH_TRITON,
            f"{full} is stdlib/torch/triton (always-available, never "
            f"severed; explicit handled category -- not silently dropped)",
            False,
        )

    if top in CLASS_D_PKGS:
        return (
            CLASS_D,
            f"{full} is a Class-D stable PyPI package ({top}); "
            f"declared in pyproject.toml [project].dependencies (NOT "
            f"vendored, NOT shimmed)",
            False,
        )

    # Unknown non-vllm/sglang third-party: not on the Class-D allowlist
    # and not stdlib/torch/triton. Surface it as a BLOCKED-candidate --
    # the plan forbids a silently-dropped third state.
    return (
        CLASS_D,
        f"unaudited third-party package {top!r} (not on the Class-D "
        f"allowlist, not stdlib/torch/triton) -> BLOCKED-candidate: "
        f"either add to pyproject.toml dependencies with a proof or "
        f"vendor it; never silently ignored",
        True,
    )


# ───────────────────────────────────────────────────────────────────────────
# U1: symbol-level reachable-closure classifier
# ───────────────────────────────────────────────────────────────────────────
def _collect_module_scope_seeds(tree: ast.Module) -> list[ast.stmt]:
    """ALL module-scope executable / import / decorator statements.

    Plan U1 FIX [confirmed]: import-time side effects
    (direct_register_custom_op, logger=init_logger,
    FP8_DTYPE=current_platform.fp8_dtype(), top-level env reads,
    module-level @triton.autotune) MUST be seeds, never silently
    dropped. We treat *every* top-level statement as a seed (the
    entrypoint is also top-level, so this is a strict superset of
    "entrypoint + side-effect statements").
    """
    return list(tree.body)


def _imports_in_stmts(
    stmts: list[ast.stmt],
) -> list[tuple[str, str, str, ast.stmt]]:
    """Yield ``(module, orig_name, local_alias, stmt)`` for every import
    reachable in these statements (recursively walks function/class
    bodies).

    ``orig_name`` is the ORIGINAL imported dotted name -- the symbol as
    it exists upstream -- used for classification + artifact. The
    ``local_alias`` (``import X as Y`` / ``from M import N as Y``) is
    kept ONLY for reference; classifying by the alias would mis-name
    ``from vllm import _custom_ops as ops`` as ``vllm.ops`` and
    Class-A it under the wrong name (plan FIX 4 / L3_02:26).
    """
    out: list[tuple[str, str, str, ast.stmt]] = []
    for s in stmts:
        for n in ast.walk(s):
            if isinstance(n, ast.Import):
                for a in n.names:
                    # `import a.b.c as x`: original dotted name is
                    # `a.b.c`; local alias is `x` (or `a` when bare).
                    orig = a.name
                    alias = a.asname or a.name
                    out.append((orig, orig, alias, n))
            elif isinstance(n, ast.ImportFrom):
                # Relative imports (n.level > 0) resolve into the
                # upstream package -- plan: relative-import -> Class A.
                mod = n.module or ""
                if n.level and n.level > 0:
                    mod = f"{'.' * n.level}{mod}"
                for a in n.names:
                    # `from M import N as Y`: original name is `N`,
                    # local alias `Y`. Classify/artifact under `M.N`.
                    out.append((mod, a.name, a.asname or a.name, n))
    return out


def classify_task(task_id: str, kernel_src: str) -> TaskClassification:
    """Symbol-level reachable-closure classifier for one task.

    BFS seeds = entrypoint + ALL module-scope statements. Every
    external (vllm/sglang) symbol is classified into exactly one of
    A / B-rewrite-public / B-inert-shim / C / S / D. unknown -> A.
    Cycle / depth-limit ⇒ T3 / BLOCKED-candidate (never silent
    truncate).
    """
    tc = TaskClassification(task_id=task_id)
    try:
        tree = ast.parse(kernel_src)
    except SyntaxError as e:
        tc.blocked = True
        tc.blocked_reason = f"kernel.py SyntaxError line {e.lineno}: {e.msg}"
        tc.tier = "T3"
        return tc

    seeds = _collect_module_scope_seeds(tree)

    # Detect a `@triton.jit`-only file with no host launcher (14 tasks):
    has_run = any(
        isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name == "run"
        for n in tree.body
    )
    jit_funcs = [
        n
        for n in tree.body
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
        and any(
            "triton.jit" in ast.unparse(d) or d_id(d) == "jit"
            for d in n.decorator_list
        )
    ]
    host_funcs = [
        n
        for n in tree.body
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
        and n not in jit_funcs
    ]
    jit_only = bool(jit_funcs) and not host_funcs and not has_run
    if jit_only:
        tc.diagnostics.append("jit-only: needs deterministic launcher template (U5)")
    if len(jit_funcs) >= 2:
        tc.diagnostics.append(
            f"multi-kernel pipeline ({len(jit_funcs)} @triton.jit) -- host orchestration"
        )

    # BFS over imports reachable from seeds. Each import edge is one
    # closure step; we track depth + a visited set for cycle/limit.
    # Queue items: (module, orig_name, local_alias, depth). Classify
    # by the ORIGINAL imported name (orig_name), never the local alias.
    imports = _imports_in_stmts(seeds)
    visited: set[str] = set()
    queue: list[tuple[str, str, str, int]] = []
    for mod, orig, alias, _ in imports:
        queue.append((mod, orig, alias, 0))

    classified: dict[str, SymbolClass] = {}
    depth_seen = 0
    while queue:
        mod, bound, alias, depth = queue.pop(0)
        depth_seen = max(depth_seen, depth)
        key = f"{mod}::{bound}"
        if key in visited:
            # Re-encountering an already-visited symbol at depth > 0
            # means a transitive-closure cycle (plan U1/U2: cycle ⇒ T3
            # BLOCKED-candidate, never silent truncate or infinite loop).
            if depth > 0:
                tc.cycle_detected = True
            continue
        visited.add(key)

        if depth > MAX_CLOSURE_DEPTH:
            tc.depth_exceeded = True
            tc.diagnostics.append(
                f"closure depth > {MAX_CLOSURE_DEPTH} at {key}"
            )
            continue
        if len(classified) > MAX_CLOSURE_SYMBOLS:
            tc.depth_exceeded = True
            tc.diagnostics.append(
                f"closure size > {MAX_CLOSURE_SYMBOLS} symbols"
            )
            break

        alias_note = "" if alias == bound else f" (local alias `{alias}`)"

        # Relative import -> resolves into upstream package -> Class A.
        if mod.startswith("."):
            sc = SymbolClass(
                symbol=f"{mod}.{bound}",
                module=mod,
                name=bound,
                cls=CLASS_A,
                proof=f"relative import resolves into upstream package{alias_note}",
                is_seed=(depth == 0),
            )
            classified[f"{mod}.{bound}"] = sc
            continue

        if not _is_external_module(mod):
            # NOT a severable vllm/sglang surface. The plan invariant
            # ("no symbol silently dropped: every symbol -> A | B-proof
            # | C | S | D | BLOCKED-candidate") forbids dropping these
            # silently. Classify EVERY external import:
            #   * stdlib / torch / triton -> CLASS_TORCH_TRITON (handled,
            #     always-available, never severed -- explicit category)
            #   * stable third-party PyPI (einops, ...) -> CLASS_D + proof
            #   * anything else -> CLASS_D-doubtful is unsafe; an unknown
            #     non-vllm/sglang package we cannot prove stable is a
            #     BLOCKED-candidate (NOT silently ignored).
            ext_cls, ext_proof, ext_blocked = _classify_non_severable(mod, bound)
            sc = SymbolClass(
                symbol=f"{mod}.{bound}",
                module=mod,
                name=bound,
                cls=ext_cls,
                proof=ext_proof + (alias_note if ext_proof else ""),
                is_seed=(depth == 0),
            )
            if ext_blocked:
                sc.blocked_reason = ext_proof
                tc.blocked_candidate = True
                tc.diagnostics.append(ext_proof)
            classified[f"{mod}.{bound}"] = sc
            continue

        cls, proof = _classify_module_member(mod, bound)
        sc = SymbolClass(
            symbol=f"{mod}.{bound}",
            module=mod,
            name=bound,
            cls=cls,
            proof=proof + (alias_note if proof else ""),
            is_seed=(depth == 0),
        )
        classified[f"{mod}.{bound}"] = sc

        # Class A symbols need transitive closure into the upstream
        # source. We attempt to resolve & parse the upstream module
        # and enqueue its own imports (depth+1).
        if cls == CLASS_A:
            sub = _resolve_and_parse_upstream(mod)
            if sub is not None:
                for smod, sorig, salias, _ in _imports_in_stmts(sub.body):
                    queue.append((smod, sorig, salias, depth + 1))
            elif _is_external_module(mod):
                # Couldn't resolve a vllm/sglang module on disk  ->
                # unvendorable ⇒ BLOCKED-candidate (never dropped).
                tc.blocked_candidate = True
                sc.blocked_reason = f"unvendorable: {mod} not resolvable under infer/"
                tc.diagnostics.append(sc.blocked_reason)

    tc.symbols = list(classified.values())
    # `severable` = symbols that actually have to be vendored/shimmed/
    # pinned/decided. CLASS_TORCH_TRITON entries (stdlib/torch/triton)
    # are recorded so they are NEVER silently dropped (plan FIX 4
    # invariant) but they are handled-and-non-severable, so they do
    # NOT count toward closure size / tier (preserves T0 semantics:
    # a plain torch+triton kernel is still T0).
    severable = [s for s in tc.symbols if s.cls != CLASS_TORCH_TRITON]
    tc.closure_size = len(severable)

    # BLOCKED determination (hard gate, plan §invariant 4):
    #  - cycle/depth ⇒ T3 BLOCKED-candidate (never silent truncate)
    #  - Class-C with NO reachable triton fallback ⇒ BLOCKED
    #  - unvendorable / unauditable ⇒ BLOCKED-candidate
    has_c = bool(tc.by_class(CLASS_C))
    has_triton_path = "@triton.jit" in kernel_src or bool(jit_funcs)
    if has_c and not has_triton_path:
        tc.blocked = True
        tc.blocked_reason = "Class-C accel symbols but NO reachable triton fallback (no @triton.jit)"
    if tc.cycle_detected:
        tc.blocked_candidate = True
        tc.diagnostics.append("closure cycle detected -> T3 BLOCKED-candidate")
    if tc.depth_exceeded:
        tc.blocked_candidate = True

    # Tier assignment (plan U1):
    #  T0: closure only torch+triton (no external symbols at all)
    #  T1: only provably-inert B (B-inert-shim / B-rewrite-public)
    #  T2: shallow A (few A symbols, converges)
    #  T3: deep (many A / multi-kernel pipeline / torch.ops.vllm.* /
    #      large closure / cycle / no-triton-path)
    a_syms = tc.by_class(CLASS_A)
    rel_syms = [s for s in severable if s.module.startswith(".")]
    b_syms = tc.by_class(CLASS_B_INERT_SHIM) + tc.by_class(CLASS_B_REWRITE_PUBLIC)
    deep_signals = (
        tc.cycle_detected
        or tc.depth_exceeded
        or len(jit_funcs) >= 2
        or len(a_syms) + len(rel_syms) >= 4
        or tc.closure_size >= 12
        or any("torch.ops.vllm" in ast.unparse(tree) for _ in [0])
        or (has_c and not has_triton_path)
    )
    if deep_signals:
        # Deep signals (multi-kernel pipeline, cycle, depth, large
        # closure, no-triton-path) force T3 even with zero external
        # symbols -- host orchestration is itself deep entanglement.
        tc.tier = "T3"
    elif not severable:
        # Only torch+triton(+stdlib) -> nothing to sever -> T0.
        tc.tier = "T0"
    elif a_syms or rel_syms or tc.by_class(CLASS_C) or tc.by_class(CLASS_S):
        tc.tier = "T2"
    elif b_syms and not a_syms:
        tc.tier = "T1"
    else:
        tc.tier = "T2"

    if "torch.ops.vllm" in kernel_src:
        tc.tier = "T3"
        tc.diagnostics.append("torch.ops.vllm.* present -> T3")

    return tc


def d_id(dec: ast.expr) -> str:
    """Best-effort decorator attribute tail name."""
    if isinstance(dec, ast.Attribute):
        return dec.attr
    if isinstance(dec, ast.Name):
        return dec.id
    if isinstance(dec, ast.Call):
        return d_id(dec.func)
    return ""


_UPSTREAM_PARSE_CACHE: dict[str, ast.Module | None] = {}


def _resolve_and_parse_upstream(module: str) -> ast.Module | None:
    """Resolve a `vllm.*`/`sglang.*` module to a file under infer/ and
    parse it. Cached. Returns None when unresolvable (⇒ caller marks
    BLOCKED-candidate)."""
    if module in _UPSTREAM_PARSE_CACHE:
        return _UPSTREAM_PARSE_CACHE[module]
    top = _module_top(module)
    if top == "vllm":
        base = VLLM_ROOT
        rel = module.replace(".", "/")
    elif top == "sglang":
        base = SGLANG_ROOT
        rel = module.replace(".", "/")
    else:
        _UPSTREAM_PARSE_CACHE[module] = None
        return None
    candidates = [base / f"{rel}.py", base / rel / "__init__.py"]
    for c in candidates:
        if c.is_file():
            try:
                tree = ast.parse(c.read_text(encoding="utf-8", errors="replace"))
            except (SyntaxError, OSError):
                tree = None
            _UPSTREAM_PARSE_CACHE[module] = tree
            return tree
    _UPSTREAM_PARSE_CACHE[module] = None
    return None


