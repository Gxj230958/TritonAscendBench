def _release_blocker_count() -> int:
    """Real S6 release-gate blocker count from the single source of
    truth (W1.5 / FIX 3 / U7): MUST match `validate_tasks.py
    --release-gate`'s blocker count.

    A task blocks release iff it is score-eligible AND its COMPOSITE
    `release_status != PASS`, where (DESIGN-V2 §4.4)::

        release_status == PASS
            <=> phase_a_prime.status == PASS AND cost_model.status == PASS

    Uses the SAME shared `eligibility.compute_release_blocking` that
    `validate_tasks.py --release-gate` and `cli.py` analyze use, so the
    S6 verdict's blocker count is identical to theirs by construction
    (not merely a numeric coincidence on a 0-PASS dev box)."""
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))
    from triton_ascend_bench.dataset import iter_all_tasks
    from triton_ascend_bench.eligibility import (
        compute_release_blocking,
        compute_score_eligible,
    )

    tasks = iter_all_tasks()
    eligible_ids = compute_score_eligible(tasks)
    return len(compute_release_blocking(tasks, eligible_ids))


def cmd_run(args: argparse.Namespace) -> int:
    task_dirs = _iter_task_dirs(args.task)
    results: list[TaskClassification] = []
    task_dirs_by_id: dict[str, Path] = {}
    for td in task_dirs:
        kp = td / "kernel.py"
        if not kp.is_file():
            continue
        tc = classify_task(td.name, kp.read_text(encoding="utf-8", errors="replace"))
        if args.tier != "all" and tc.tier != args.tier:
            continue
        results.append(tc)
        task_dirs_by_id[td.name] = td
    gpu = _cuda_available()
    # W1.5: the S6 verdict's blocker count is the COMPOSITE release
    # predicate's blocking-set size -- identical to `validate_tasks.py
    # --release-gate` (both call `eligibility.compute_release_blocking`).
    release_blocker_count = _release_blocker_count()
    PLANS_DIR.mkdir(parents=True, exist_ok=True)
    STATUS_MD.write_text(
        _render_status_md(
            results, gpu, release_blocker_count, task_dirs_by_id
        )
    )
    # Unit 2.3: SKIPPED_BY_DESIGN tally is read from each task's
    # meta.phase_a_prime (the authoritative source -- the row in
    # status.md is derived from it, not vice versa).
    n_skipped_by_design = 0
    for td in task_dirs_by_id.values():
        try:
            m = yaml.safe_load((td / "meta.yaml").read_text()) or {}
        except (OSError, yaml.YAMLError):
            continue
        pap = m.get("phase_a_prime") or {}
        if (
            pap.get("skip_invocation") is True
            or pap.get("status") == "SKIPPED_BY_DESIGN"
        ):
            n_skipped_by_design += 1
    print(
        f"run: {len(results)} tasks (tier={args.tier}) "
        f"release-blockers={release_blocker_count} "
        f"skipped_by_design={n_skipped_by_design} -> "
        f"{STATUS_MD.relative_to(REPO_ROOT)}  "
        f"(GPU={'yes' if gpu else 'no'})"
    )
    return 0


# ───────────────────────────────────────────────────────────────────────────
# Entrypoint-closure slice (severance for whole-module vendored kernels)
# ───────────────────────────────────────────────────────────────────────────
# Module-level names a sliced standalone may reference for free without a
# vendored def -- the std/triton/torch surface the bench already provides
# verbatim. Anything outside this set that the entrypoint closure references
# would have to be vendored, so the slice fails closed (returns the original
# source untouched and the existing line-rewrite/leak audit takes over).
# Restricted to exactly the names the slice header re-provides -- a closure
# free name outside this set (e.g. an `F` torch.nn.functional alias the header
# does not emit) would yield a NameError-broken slice the syntax-only parse
# guard cannot catch, so it must decline instead.
_SLICE_FREE_NAME_ALLOW = frozenset({"torch", "triton", "tl", "math"})


def _has_top_level_flashinfer_import(tree: "ast.Module") -> bool:
    """True iff the module has a MODULE-LEVEL (executed at import) ``import
    flashinfer`` / ``from flashinfer... import ...`` statement. A flashinfer
    import nested inside a function body (lazy, only run when that off-path
    helper is called) does NOT count -- those modules import fine without a
    flashinfer stub, so the launcher slice must not fire for them."""
    for node in tree.body:  # top-level statements only (not ast.walk)
        if isinstance(node, ast.Import):
            if any(a.name.split(".", 1)[0] == "flashinfer" for a in node.names):
                return True
        elif isinstance(node, ast.ImportFrom):
            mod = node.module or ""
            if mod == "flashinfer" or mod.startswith("flashinfer."):
                return True
    return False


def _has_top_level_dead_vllm_import(
    tree: "ast.Module", src: str, task_dir: "Path | None"
) -> bool:
    """True iff the module has a MODULE-LEVEL ``from vllm/sglang... import X``
    whose binding ``X`` is referenced by NO def in the launcher's launched-jit
    transitive closure -- i.e. an upstream import that feeds only DEAD siblings
    (the host-wrapper class / off-path helpers the launcher bypasses). Such an
    import is dead weight on the graded launch path, so the entrypoint-closure
    slice can drop it (and its dead siblings) while keeping the launched jit
    byte-identical.

    This is the launcher-task analogue of ``_has_top_level_flashinfer_import``:
    it gates the slice for a jit-only launcher whose stray upstream import is
    vllm/sglang rather than flashinfer. It is strictly NARROWER than "any
    top-level vllm import": it fires ONLY for imports whose binding is provably
    off the launched-jit closure. A launcher whose launched jit (or its def-to-
    def closure) references the imported symbol returns False, so that symbol
    stays a real import the line rewriter / frozen shim must handle.

    Firing the slice for such a launcher is safe regardless of how that task
    PREVIOUSLY severed (full-module line-rewrite vs. slice): the slice is itself
    fail-closed -- it only returns sliced source when every kept def's free
    names are in the std/triton/torch allow-set AND the result carries no
    residual vllm/sglang import; otherwise it declines and the original
    full-module path runs unchanged. So a task that needs the symbol on its
    graded path can never be silently narrowed by this gate. Fail-closed:
    returns False whenever the launcher / launched roots cannot be resolved.
    """
    if task_dir is None:
        return False
    # Collect kernel.py @triton.jit names so the off-closure check can resolve
    # the launched roots against them.
    jit_names: set[str] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            for d in getattr(node, "decorator_list", []):
                src_d = ast.get_source_segment(src, d) or ""
                if "triton.jit" in src_d or src_d.strip().endswith("jit"):
                    jit_names.add(node.name)
    if not _launcher_launched_jit_roots(task_dir, jit_names, kernel_src=src):
        return False  # no provable graded root -> cannot prove dead -> decline
    for node in tree.body:  # top-level statements only (not ast.walk)
        if not isinstance(node, ast.ImportFrom):
            continue
        top = (node.module or "").split(".", 1)[0]
        if top not in {"vllm", "sglang"}:
            continue
        for alias in node.names:
            bound = alias.asname or alias.name
            if _symbol_off_launched_closure(src, task_dir, bound):
                return True
    return False


def _jit_launches_in(node: ast.AST, jit_names: set[str]) -> set[str]:
    """Collect kernel.py @triton.jit names launched (``NAME[grid](...)`` /
    ``obj.NAME[grid](...)``) anywhere under ``node``, restricted to ``jit_names``."""
    found: set[str] = set()
    for n in ast.walk(node):
        if not isinstance(n, ast.Call) or not isinstance(n.func, ast.Subscript):
            continue
        base = n.func.value
        if isinstance(base, ast.Name):
            nm = base.id
        elif isinstance(base, ast.Attribute):
            nm = base.attr
        else:
            continue
        if nm in jit_names:
            found.add(nm)
    return found


def _launcher_launched_jit_roots(
    task_dir: "Path | None", jit_names: set[str], kernel_src: "str | None" = None
) -> set[str]:
    """Return the kernel.py ``@triton.jit`` kernels that ``_pa_launcher.py``
    drives, restricted to the kernel's own jit names.

    Used by the entrypoint-closure slice for jit-only launcher tasks, where
    ``meta.gpu_triton`` is the launcher's ``run`` rather than a kernel.py def.
    The launched kernels are the real graded roots; their transitive closure is
    what the slice must keep.

    Two launch forms are recognised:

      * DIRECT: a subscript-then-call ``NAME[grid](...)`` / ``obj.NAME[grid](...)``
        in the launcher, where ``NAME`` is a kernel.py jit name (the launcher may
        reach the kernel via a module alias, e.g. ``_kmod._foo_kernel[grid]``).
      * VIA HOST WRAPPER: a plain call ``NAME(...)`` in the launcher where
        ``NAME`` is an in-module kernel.py ``def`` (a host wrapper) that itself
        launches jit kernels. The wrapper's launched jit kernels are the real
        graded roots. Wrapper-calls-wrapper nesting is resolved transitively so
        the root set is COMPLETE; an in-module wrapper whose body we cannot
        resolve makes the function fail closed (returns the empty set, so the
        caller declines the off-path shim and the dependency surfaces) rather
        than trusting a partial root set.

    ``kernel_src`` is the frozen kernel.py source (needed to map host wrappers to
    the jit kernels they launch). When omitted only DIRECT launches are detected
    (legacy behaviour). Fail-closed throughout: unknown targets are ignored and
    an empty result makes the caller decline the slice."""
    if task_dir is None:
        return set()
    launcher = task_dir / "_pa_launcher.py"
    if not launcher.is_file():
        return set()
    try:
        ltree = ast.parse(launcher.read_text(encoding="utf-8", errors="replace"))
    except (OSError, SyntaxError):
        return set()

    # Map each in-module kernel.py host wrapper (plain def) to the jit kernels it
    # launches, resolving wrapper-calls-wrapper nesting transitively.
    wrapper_jits: dict[str, set[str]] = {}
    if kernel_src:
        try:
            ktree = ast.parse(kernel_src)
        except SyntaxError:
            return set()
        kdefs: dict[str, ast.AST] = {}
        for node in ktree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                # Host wrappers are plain defs; the jit kernels themselves carry
                # a @triton.jit decorator and are NOT host wrappers.
                is_jit = any(
                    "triton.jit" in (ast.get_source_segment(kernel_src, d) or "")
                    or (ast.get_source_segment(kernel_src, d) or "").strip().endswith("jit")
                    for d in getattr(node, "decorator_list", [])
                )
                if not is_jit:
                    kdefs[node.name] = node
        # Direct jit launches inside each wrapper + the in-module wrappers it calls.
        direct: dict[str, set[str]] = {}
        calls: dict[str, set[str]] = {}
        for name, node in kdefs.items():
            direct[name] = _jit_launches_in(node, jit_names)
            callees: set[str] = set()
            for n in ast.walk(node):
                if not isinstance(n, ast.Call):
                    continue
                # In-module wrapper-calls-wrapper, bare or attribute form
                # (``foo(...)`` / ``mod.foo(...)``). Both are traced so a
                # wrapper that reaches a jit via a nested aliased wrapper call
                # is never under-included.
                if isinstance(n.func, ast.Name):
                    cname = n.func.id
                elif isinstance(n.func, ast.Attribute):
                    cname = n.func.attr
                else:
                    continue
                if cname in kdefs:
                    callees.add(cname)
            calls[name] = callees
        # Transitive closure of launched jit kernels per wrapper.
        for name in kdefs:
            seen: set[str] = set()
            stack = [name]
            jits: set[str] = set()
            while stack:
                w = stack.pop()
                if w in seen:
                    continue
                seen.add(w)
                jits |= direct.get(w, set())
                stack.extend(calls.get(w, set()))
            wrapper_jits[name] = jits

    roots: set[str] = set()
    for node in ast.walk(ltree):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        # DIRECT launch: NAME[grid](...) / obj.NAME[grid](...).
        if isinstance(func, ast.Subscript):
            base = func.value
            if isinstance(base, ast.Name):
                name = base.id
            elif isinstance(base, ast.Attribute):
                name = base.attr
            else:
                continue
            if name in jit_names:
                roots.add(name)
            continue
        # VIA HOST WRAPPER: NAME(...) or obj.NAME(...) where NAME is an
        # in-module wrapper (the launcher may reach the wrapper bare or via a
        # module alias, e.g. ``_kmod.chunk_state_varlen(...)``). Both forms are
        # collected so an aliased wrapper call is never silently under-included
        # (which would drop a real graded jit root and wrongly mark a symbol
        # off-path); over-inclusion stays safe because the downstream
        # ``_symbol_off_launched_closure`` re-checks the symbol against every
        # kept def.
        if isinstance(func, ast.Name):
            wname = func.id
        elif isinstance(func, ast.Attribute):
            wname = func.attr
        else:
            wname = None
        if wname is not None and wname in wrapper_jits:
            roots |= wrapper_jits[wname]
    return roots


def _symbol_off_launched_closure(
    src: str, task_dir: "Path | None", symbol: str
) -> bool:
    """Return True iff ``symbol`` is referenced by NO kernel.py def in the
    transitive module-level def-to-def closure of the @triton.jit kernels the
    task's ``_pa_launcher.py`` actually launches.

    Used to fail-closed gate a relative-import shim: a symbol an off-path
    sibling jit kernel imports (and only that sibling references) is safe to
    redirect to an inert raising stub, because the graded launch never traces
    that sibling. Fail-closed: returns False (NOT off-path -> do NOT shim ->
    leak surfaces) whenever the launcher / launched roots cannot be resolved,
    the source does not parse, or ANY kept def references the symbol.

    The closure walks module-level def/class references only; it does not
    chase a top-level alias (``sp = symbol``) re-exported into a kept def.
    That under-count is harmless for the gated shim: the redirected stub
    RAISES on call, so a graded path that somehow reached it via an alias
    would fail loudly (never silently pass). The vendored chunk_state /
    chunk_cumsum sources reference the symbol directly, so the
    direct-reference closure is exact for the corpus this gates."""
    if task_dir is None:
        return False
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return False
    defs: dict[str, ast.AST] = {}
    jit_names: set[str] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            defs[node.name] = node
            for d in getattr(node, "decorator_list", []):
                src_d = ast.get_source_segment(src, d) or ""
                if "triton.jit" in src_d or src_d.strip().endswith("jit"):
                    jit_names.add(node.name)
    roots = _launcher_launched_jit_roots(task_dir, jit_names, kernel_src=src)
    if not roots:
        return False  # no provable graded root -> cannot prove off-path

    def _names_in(node: ast.AST) -> set[str]:
        out: set[str] = set()
        for n in ast.walk(node):
            if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load):
                out.add(n.id)
        return out

    keep: set[str] = set()
    work = list(roots)
    while work:
        name = work.pop()
        if name in keep:
            continue
        keep.add(name)
        node = defs.get(name)
        if node is None:
            continue
        for ref in _names_in(node):
            if ref in defs and ref not in keep:
                work.append(ref)
    for name in keep:
        node = defs.get(name)
        if node is not None and symbol in _names_in(node):
            return False  # graded closure reaches the symbol -> keep real import
    return True


def _slice_to_entrypoint_closure(
    src: str, task_dir: "Path | None"
) -> "str | None":
    """Reduce a whole-module vendored ``kernel.py`` to just the graded
    entrypoint's transitive module-level closure.

    Some vendored kernels copy an ENTIRE upstream module (e.g. vLLM
    ``gdn_linear_attn.py``): the graded op is a small tail, but the file's
    head is dead upstream classes plus heavy ``vllm`` imports / module-level
    custom-op registrations. The line-level import rewrite cannot sever those
    (their symbols feed the dead classes, not the graded op), so the severed
    import audit correctly flags a ``vllm`` leak.

    This slice keeps ONLY: (a) the graded entrypoint (from
    ``meta.oracle.gpu_triton``) and the ``@triton.jit`` kernels it launches,
    (b) the transitive closure of OTHER module-level ``def``/``class`` that
    those reference, and (c) the std imports (``torch``/``triton``/``tl``)
    the closure needs. Each kept symbol is emitted as its EXACT source span
    (decorators included -- ``@triton.jit`` MUST survive), so the kernel
    under test is byte-identical; only dead siblings and their imports are
    dropped.

    Fail-closed: returns ``None`` (slice declined; caller keeps the original
    source) unless the source actually carries a ``vllm``/``sglang`` import
    AND the entrypoint closure resolves cleanly with no free name outside
    ``_SLICE_FREE_NAME_ALLOW``. So a task whose entrypoint genuinely needs an
    upstream symbol is never silently narrowed -- the leak surfaces instead.
    """
    if task_dir is None:
        return None
    # Only meaningful when the module actually leaks upstream imports.
    if not re.search(r"^\s*(?:from|import)\s+(?:vllm|sglang)\b", src, re.M):
        return None
    ep_name = _entrypoint_from_meta(task_dir)
    if not ep_name or ep_name == "placeholder":
        return None
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return None

    # Index top-level defs/classes by name; collect @triton.jit names.
    defs: dict[str, ast.AST] = {}
    jit_names: set[str] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            defs[node.name] = node
            for d in getattr(node, "decorator_list", []):
                src_d = ast.get_source_segment(src, d) or ""
                if "triton.jit" in src_d or src_d.strip().endswith("jit"):
                    jit_names.add(node.name)

    # Closure roots. The normal case: meta.gpu_triton names an in-module def
    # (the upstream host wrapper or a bare jit). For a launcher-driven jit-only
    # task the meta entrypoint is the launcher's ``run`` (NOT a kernel.py def),
    # so derive the roots from the @triton.jit kernels the launcher LAUNCHES.
    #
    # The launcher branch activates when the module carries a MODULE-LEVEL
    # (top-of-file, executed at import) upstream import that is dead weight on
    # the graded launch path:
    #   * a non-vllm/sglang third-party (``from flashinfer import ...`` at
    #     column 0), or
    #   * a vllm/sglang import whose binding feeds ONLY dead siblings (the
    #     L3_07 pattern: ``from vllm.distributed.parallel_state import
    #     GroupCoordinator`` used only by the off-path _cp_lse_* helpers, never
    #     by the launched jit closure -- and also the L1_02/L1_05/L1_28 pattern,
    #     where the launcher reconstructs the value the dead host-wrapper class
    #     fetched from the import). In both cases the slice keeps the launched
    #     jit byte-identical and drops the dead import.
    # A flashinfer import that is LAZY inside a function body (L1_32/L1_33/
    # L2_18/L2_38 -- never run at import on the graded path) is NOT a top-level
    # import, so neither probe fires and the slice declines, leaving those
    # tasks' established severance untouched. The slice is fail-closed
    # downstream regardless: it returns sliced source only when every kept def's
    # free names are std/triton/torch and the result carries no residual
    # vllm/sglang import, so a launcher that genuinely needs an upstream symbol
    # on its graded path is never silently narrowed -- the slice declines and
    # the full-module path runs. Fail-closed here too: if no launched jit root
    # resolves into the kernel's jit_names, decline so the leak surfaces.
    if ep_name in defs:
        ep_roots = {ep_name}
    elif _has_top_level_flashinfer_import(tree) or _has_top_level_dead_vllm_import(
        tree, src, task_dir
    ):
        ep_roots = _launcher_launched_jit_roots(task_dir, jit_names, kernel_src=src)
        if not ep_roots:
            return None
    else:
        return None

    def _names_in(node: ast.AST) -> set[str]:
        out: set[str] = set()
        for n in ast.walk(node):
            if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load):
                out.add(n.id)
        return out

    # Transitive closure over module-level defs the entrypoint reaches.
    keep: set[str] = set()
    work = list(ep_roots)
    while work:
        name = work.pop()
        if name in keep:
            continue
        keep.add(name)
        node = defs.get(name)
        if node is None:
            continue
        for ref in _names_in(node):
            if ref in defs and ref not in keep:
                work.append(ref)

    # Free names the kept closure references that are NOT a kept def -- they
    # must all be in the allow-set (std/triton/torch surface) or the slice is
    # unsafe (would need vendoring). Builtins are fine.
    import builtins as _bi
    _builtin_names = set(dir(_bi))
    free: set[str] = set()
    for name in keep:
        node = defs.get(name)
        if node is None:
            continue
        # Locals = params + every name bound inside the def (assignment
        # targets, for-loop vars, comprehension vars, walrus, with/except
        # aliases). A free name is one that is only ever LOADED and is not a
        # kept def / builtin -- those must be in the std allow-set.
        local: set[str] = set()
        for fn in ast.walk(node):
            if isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)):
                local.add(fn.name)
                local.update(
                    a.arg
                    for a in list(fn.args.args)
                    + list(fn.args.posonlyargs)
                    + list(fn.args.kwonlyargs)
                )
                if fn.args.vararg:
                    local.add(fn.args.vararg.arg)
                if fn.args.kwarg:
                    local.add(fn.args.kwarg.arg)
        for sub in ast.walk(node):
            if isinstance(sub, ast.Name) and isinstance(
                sub.ctx, (ast.Store, ast.Del)
            ):
                local.add(sub.id)
        for ref in _names_in(node):
            if ref in keep or ref in local or ref in _builtin_names:
                continue
            free.add(ref)
    if not free <= _SLICE_FREE_NAME_ALLOW:
        return None  # closure needs an upstream symbol -> do not narrow

    # Emit: minimal std imports the closure uses + each kept def verbatim
    # (decorators preserved), in original source order.
    header: list[str] = []
    if "torch" in free or "torch" in ep_roots:
        header.append("import torch")
    if "triton" in free:
        header.append("import triton")
    if "tl" in free:
        header.append("import triton.language as tl")
    if "math" in free:
        header.append("import math")
    # torch is always safe to provide (host wrappers allocate output tensors).
    if "import torch" not in header:
        header.insert(0, "import torch")

    lines = src.splitlines()
    kept_nodes = [
        defs[n] for n in defs if n in keep
    ]
    kept_nodes.sort(key=lambda nd: getattr(nd, "lineno", 0))
    blocks: list[str] = []
    for nd in kept_nodes:
        start = min(
            [d.lineno for d in getattr(nd, "decorator_list", [])]
            + [nd.lineno]
        )
        end = nd.end_lineno
        blocks.append("\n".join(lines[start - 1 : end]))

    sliced = (
        "# Phase A': sliced to the graded entrypoint's module-level closure\n"
        "# (whole-module vendored kernel; dead upstream siblings + their\n"
        "# upstream imports dropped -- the kept defs are byte-identical).\n"
        + "\n".join(header)
        + "\n\n\n"
        + "\n\n\n".join(blocks)
        + "\n"
    )
    # Final guard: the sliced text must itself carry no upstream import and
    # parse. Scan only import statements so a benign token in a kept comment/
    # identifier never trips it (the slice's own banner is import-free here).
    if re.search(
        r"^\s*(?:from|import)\s+(?:vllm|sglang)\b", sliced, re.M
    ):
        return None
    try:
        ast.parse(sliced)
    except SyntaxError:
        return None
    return sliced


