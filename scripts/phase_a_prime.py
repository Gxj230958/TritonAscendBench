def _entrypoint_from_meta(task_dir: Path) -> str | None:
    """The upstream callable name from ``meta.yaml: oracle.gpu_triton``
    (``kernel.py::<name>``). This is the UNMODIFIED upstream entrypoint
    both the original side (real code) and the synthesised severed
    ``run()`` wrapper target -- it is NOT ``run`` (current task
    kernel.py never exposes ``run``; the circular-flow bug, HOLE B)."""
    mp = task_dir / "meta.yaml"
    if not mp.is_file():
        return None
    try:
        meta = yaml.safe_load(mp.read_text())
    except (OSError, ValueError):
        return None
    gt = (meta.get("oracle") or {}).get("gpu_triton")
    if isinstance(gt, str) and "::" in gt:
        return gt.split("::", 1)[1].strip()
    return gt if isinstance(gt, str) else None


def _resolve_upstream_entrypoint(task_dir: Path) -> tuple[bool, str | None, str]:
    """Resolve a task's UPSTREAM entrypoint exactly the way
    ``s2_verify_task`` -> ``_run_s2_pair`` -> ``_resolve_entrypoint``
    does, WITHOUT running anything.

    BLOCKER 2 (codex r3 [confirmed]): 96/101 task metas point
    ``oracle.gpu_triton`` at ``kernel.py::placeholder`` and NO task
    kernel defines ``placeholder``; the real S2 flow BLOCKS at
    entrypoint resolution (``_pa_subproc_runner._resolve_entrypoint``
    returns a non-callable -> the original side returns rc=2 ->
    ``s2_verify_task`` never reaches the CUDA gate). The status report
    MUST therefore distinguish:

      * resolvable upstream callable + no GPU here ⇒ ``UNRUN(needs-gpu)``
        (honest: it WOULD reach the CUDA-authoritative gate), vs
      * unresolvable / ``placeholder`` / no upstream callable ⇒
        ``BLOCKED(no-upstream-entrypoint)`` (it can never even run --
        claiming UNRUN(needs-gpu) for these is the overclaim codex
        flagged).

    Returns ``(resolvable, entrypoint_name, reason)``.

    HOLE 2 (codex r4 [confirmed]): this MUST mirror
    ``_pa_subproc_runner._resolve_entrypoint`` EXACTLY so the status
    verdict never diverges from what the runner would actually do. That
    runner does, for the ORIGINAL side (real upstream kernel.py, which
    never defines ``run``):

      * ``fn = getattr(mod, name)``; resolvable iff ``callable(fn)``;
      * else FALL BACK to ``getattr(mod, "run", None)``.

    Mirrored statically (no import/exec, GPU-free, side-effect-free):

      * ``def`` / ``async def`` / ``class`` named ``ep``  -> callable.
      * top-level ``ep = <rhs>``:
          - RHS is a ``lambda``                          -> callable;
          - RHS is a literal constant (``ep = 5``, str,
            None, tuple/list/dict/set literal)           -> NOT
            callable (the runner's ``callable()`` is False) -> not
            resolvable via this name;
          - any OTHER RHS (Name / Call / Attribute / etc.) is
            STATICALLY AMBIGUOUS -> be CONSERVATIVE: treat as
            "needs-actual-verify" (resolvable=True), and HOLE 1's REAL
            S2-smoke run then settles the true outcome (we never
            optimistically claim PASS/UNRUN -- the real verify does).
      * the runner's ``run`` FALLBACK: if ``ep`` is not resolvable but
        the kernel defines a top-level ``def run`` / ``async def
        run`` / callable ``run = ...`` / ``class run``, the runner
        would still resolve (``getattr(mod, "run")``) -> resolvable.

    A statically-determinable non-callable (e.g. ``X = 5``) with no
    ``run`` fallback is the ONLY assignment case reported NOT
    resolvable; everything ambiguous defers to the real smoke run."""
    import ast as _ast

    ep = _entrypoint_from_meta(task_dir)
    if not ep:
        return False, None, (
            "meta.yaml oracle.gpu_triton missing / not kernel.py::<name>"
        )
    kp = task_dir / "kernel.py"
    try:
        src = kp.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        return False, ep, f"kernel.py unreadable: {e}"
    try:
        tree = _ast.parse(src)
    except SyntaxError as e:
        return False, ep, f"kernel.py SyntaxError line {e.lineno}: {e.msg}"

    def _static_callability(name: str):
        """(state, reason) for top-level binding of ``name``:
        state in {"callable", "not_callable", "ambiguous", "absent"} --
        mirroring the runner's ``callable(getattr(mod, name))``."""
        # A non-callable LITERAL constant the runner's callable() rejects.
        _noncallable_rhs = (
            _ast.Constant, _ast.List, _ast.Tuple, _ast.Dict, _ast.Set,
            _ast.ListComp, _ast.DictComp, _ast.SetComp, _ast.JoinedStr,
        )
        last: tuple[str, str] = ("absent", "")
        for nn in tree.body:
            if (
                isinstance(
                    nn, (_ast.FunctionDef, _ast.AsyncFunctionDef,
                         _ast.ClassDef)
                )
                and nn.name == name
            ):
                last = ("callable", "")
            elif isinstance(nn, (_ast.Assign, _ast.AnnAssign)):
                tgts = (
                    nn.targets if isinstance(nn, _ast.Assign)
                    else [nn.target]
                )
                if any(
                    isinstance(tg, _ast.Name) and tg.id == name
                    for tg in tgts
                ):
                    rhs = nn.value
                    if isinstance(rhs, _ast.Lambda):
                        last = ("callable", "")
                    elif rhs is None or isinstance(rhs, _noncallable_rhs):
                        last = (
                            "not_callable",
                            f"top-level {name!r} is bound to a "
                            f"non-callable literal (runner's "
                            f"callable(getattr) is False)",
                        )
                    else:
                        last = (
                            "ambiguous",
                            f"top-level {name!r} = <expr> is not "
                            f"statically determinable as callable; "
                            f"conservative -> deferred to real S2-smoke",
                        )
        return last

    st, why = _static_callability(ep)
    if st in ("callable", "ambiguous"):
        return True, ep, why
    # The runner's ``run`` fallback (`getattr(mod, "run", None)`):
    # a non-callable / absent ``ep`` still resolves IF a top-level
    # ``run`` is itself callable (or statically ambiguous).
    run_st, run_why = _static_callability("run")
    if run_st in ("callable", "ambiguous"):
        _wr = why or "no such module-level callable"
        _rr = run_why or "callable run defined"
        return True, ep, (
            f"meta entrypoint {ep!r} not resolvable ({_wr}) but the "
            f"runner's `run` fallback applies ({_rr})"
        )
    if st == "not_callable":
        return False, ep, (
            f"meta oracle.gpu_triton points at kernel.py::{ep} but "
            f"{why}; no callable `run` fallback either -- the runner's "
            f"original side returns rc=2 (no real upstream callable)"
        )
    return False, ep, (
        f"meta oracle.gpu_triton points at kernel.py::{ep} but no "
        f"module-level callable {ep!r} is defined in kernel.py and no "
        f"`run` fallback exists (no real upstream callable to compare "
        f"against)"
    )


