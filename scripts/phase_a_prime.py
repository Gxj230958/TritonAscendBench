def s2_smoke_compare(orig: dict, severed: dict) -> tuple[bool, str]:
    """Strict bit-exact equivalence assertion (NO ULP escape, NOT
    tolerance_class).

    Asserts dtype + shape + strides + key-set + bit-exact values for
    every output. Returns (equivalent, reason). This is the soundness
    command -- used by both S2-smoke (pre-filter, never PASS) and
    S2-gpu-authoritative.
    """
    import torch

    if set(orig.keys()) != set(severed.keys()):
        return False, f"output key-set differs: {sorted(orig)} vs {sorted(severed)}"
    for k in orig:
        a, b = orig[k], severed[k]
        if not (torch.is_tensor(a) and torch.is_tensor(b)):
            if a != b:
                return False, f"{k}: non-tensor value differs"
            continue
        if a.dtype != b.dtype:
            return False, f"{k}: dtype {a.dtype} vs {b.dtype} (NO fp32-cast escape)"
        if tuple(a.shape) != tuple(b.shape):
            return False, f"{k}: shape {tuple(a.shape)} vs {tuple(b.shape)}"
        if a.stride() != b.stride():
            return False, f"{k}: strides {a.stride()} vs {b.stride()}"
        if not torch.equal(a, b):
            return False, f"{k}: NOT bit-exact (no ULP tolerance in S2)"
    return True, "bit-exact"


def _alias_groups(meta_by_key: dict) -> list[set[str]]:
    """Partition tensor keys into alias groups: two tensors are aliased
    iff they share the same underlying STORAGE BUFFER.

    HOLE C fix: the key is ``storage_id`` (``untyped_storage().data_ptr()``
    -- the buffer BASE), NOT ``data_ptr`` (the element pointer
    ``base + storage_offset*itemsize``). Two views of ONE tensor at
    DIFFERENT offsets have different ``data_ptr`` but the SAME
    ``storage_id`` -> they ARE aliased and MUST be grouped together (the
    old data_ptr key silently missed exactly this case). Since
    ``storage_id`` is process-local but consistent WITHIN one side, the
    grouping is an intra-side equivalence relation compared structurally
    between the two sides (plan FIX 1)."""
    buckets: dict[int, set[str]] = {}
    for key, m in meta_by_key.items():
        # untyped-storage base identifies the shared buffer regardless
        # of per-view storage_offset (fall back to data_ptr only for
        # legacy manifests that predate the storage_id field).
        base = m.get("storage_id", m.get("data_ptr"))
        buckets.setdefault(base, set()).add(key)
    return [g for g in buckets.values() if len(g) >= 1]


def _normalise_alias(groups: list[set[str]]) -> set[frozenset]:
    """Canonical, position-independent representation of the alias
    relation: the set of multi-member alias groups (singletons carry no
    aliasing information)."""
    return {frozenset(g) for g in groups if len(g) >= 2}


# Process-local tensor-meta fields. They are valid for *intra-side*
# alias grouping (storage_id) but are DIFFERENT pointers in the two
# subprocesses, so they MUST be excluded from any *cross-side* metadata
# equality check -- the alias RELATIONSHIP is compared separately and
# position-independently via _alias_groups/_normalise_alias.
_PROC_LOCAL_META = ("data_ptr", "storage_id", "storage_nbytes")


def _layout_fields(m: dict) -> dict:
    """Cross-side-comparable layout view of a tensor-meta dict:
    dtype + shape + stride + storage_offset ONLY (drops process-local
    pointers). Used to compare mutated-input post-layout between the
    two S2 sides without spuriously failing on differing process
    pointers."""
    return {k: v for k, v in m.items() if k not in _PROC_LOCAL_META}


def compare_s2_manifests(
    orig_manifest: dict,
    severed_manifest: dict,
    o_side: str = "original",
    s_side: str = "severed",
) -> tuple[bool, str]:
    """Strict bit-exact comparison over the subprocess manifests
    (plan FIX 1). Compares, per shape:

      * output structure (nested dict/list/tuple shape + non-tensor
        leaves) -- structural mismatch ⇒ fail;
      * every leaf tensor: dtype + shape + stride + storage_offset +
        bit-exact value (NO tolerance, NO ULP, NO fp32-cast);
      * alias relationship: which output/input tensors share storage
        (between original and severed -- a severed kernel that drops a
        view/alias fails);
      * mutated inputs: inputs modified in-place must match between
        original and severed (same set, same post-call value+layout).
    """
    import torch
    from safetensors.torch import load_file

    om, sm = orig_manifest, severed_manifest
    o_shapes = om.get("shapes", {})
    s_shapes = sm.get("shapes", {})
    if set(o_shapes) != set(s_shapes):
        return False, (
            f"shape-id set differs: {sorted(o_shapes)} vs {sorted(s_shapes)}"
        )

    for sid in o_shapes:
        o, s = o_shapes[sid], s_shapes[sid]

        # 1. Output structure (nested / non-tensor) must match exactly.
        if _strip_tensor_keys(o["tree"]) != _strip_tensor_keys(s["tree"]):
            # Diagnostic-only: surface both descriptors so the diverging side
            # is visible (the bare phrase hides which side is nested/non-tensor).
            # Leading phrase kept intact for the category recogniser.
            return False, (
                f"{sid}: output structure differs (nested/non-tensor): "
                f"orig={_strip_tensor_keys(o['tree'])!r} sev={_strip_tensor_keys(s['tree'])!r}"
            )

        o_meta, s_meta = o["leaf_meta"], s["leaf_meta"]
        # Only OUTPUT leaves (not __mut__ inputs) for the value compare.
        o_out = {k: v for k, v in o_meta.items() if not k.startswith("__mut__")}
        s_out = {k: v for k, v in s_meta.items() if not k.startswith("__mut__")}
        if set(o_out) != set(s_out):
            return False, f"{sid}: output leaf-set differs"

        of = load_file(str(Path(om["_dir"]) / f"{o_side}_{sid}.safetensors")) \
            if o_out else {}
        sf = load_file(str(Path(sm["_dir"]) / f"{s_side}_{sid}.safetensors")) \
            if s_out else {}

        for k in o_out:
            ma, mb = o_out[k], s_out[k]
            if ma["dtype"] != mb["dtype"]:
                return False, (
                    f"{sid}/{k}: dtype {ma['dtype']} vs {mb['dtype']} "
                    f"(NO fp32-cast escape)"
                )
            if ma["shape"] != mb["shape"]:
                return False, f"{sid}/{k}: shape {ma['shape']} vs {mb['shape']}"
            if ma["stride"] != mb["stride"]:
                return False, (
                    f"{sid}/{k}: stride {ma['stride']} vs {mb['stride']}"
                )
            if ma["storage_offset"] != mb["storage_offset"]:
                return False, (
                    f"{sid}/{k}: storage_offset "
                    f"{ma['storage_offset']} vs {mb['storage_offset']}"
                )
            if not torch.equal(of[k], sf[k]):
                return False, f"{sid}/{k}: NOT bit-exact (no ULP tolerance)"

        # 2. Alias relationship (ALL outputs + ALL inputs sharing
        # storage). HOLE C: merge in_alias_meta (every input tensor's
        # storage identity, not just mutated ones) so an output that
        # aliases an UNMODIFIED input is detected -- previously only
        # output leaves + __mut__ inputs were grouped, making
        # output<->unmodified-input aliasing invisible.
        o_alias_in = o.get("in_alias_meta", {})
        s_alias_in = s.get("in_alias_meta", {})
        o_alias_all = {**o_meta, **o_alias_in}
        s_alias_all = {**s_meta, **s_alias_in}
        if _normalise_alias(_alias_groups(o_alias_all)) != _normalise_alias(
            _alias_groups(s_alias_all)
        ):
            return False, (
                f"{sid}: alias relationship differs -- severed kernel "
                f"changed which tensors share storage (incl. "
                f"output<->unmodified-input aliasing)"
            )

        # 3. Mutated-input set + post-call value/layout must match.
        o_mut, s_mut = o["mutated_inputs"], s["mutated_inputs"]
        if set(o_mut) != set(s_mut):
            return False, (
                f"{sid}: mutated-input set differs "
                f"{sorted(o_mut)} vs {sorted(s_mut)}"
            )
        for k in o_mut:
            # Compare only the cross-side-stable layout fields
            # (dtype/shape/stride/storage_offset). data_ptr/storage_id
            # are process-local -- they ALWAYS differ between the two
            # subprocesses; the alias RELATIONSHIP is checked above via
            # storage-identity grouping, not raw-pointer equality.
            if _layout_fields(o_mut[k]["post_meta"]) != _layout_fields(
                s_mut[k]["post_meta"]
            ):
                return False, (
                    f"{sid}: in-place input {k!r} post-mutation layout "
                    f"differs (dtype/shape/stride/storage_offset)"
                )
            # Mutated-input leaf bytes live in the SAME per-(side,sid)
            # safetensors file as the outputs (`of`/`sf` already loaded
            # above -- they contain every leaf incl. `__mut__*`).
            lk = o_mut[k]["leaf"]
            if lk not in of or lk not in sf:
                return False, (
                    f"{sid}: in-place input {k!r} mutated-leaf missing "
                    f"from a side's dump"
                )
            if not torch.equal(of[lk], sf[lk]):
                return False, (
                    f"{sid}: in-place input {k!r} post-mutation value "
                    f"differs (NOT bit-exact)"
                )
    return True, "bit-exact (values + alias + mutated-input)"


def _strip_tensor_keys(tree):
    """Return a copy of the structure descriptor with tensor leaf keys
    replaced by a placeholder, so two trees compare equal iff their
    *shape* (and non-tensor leaves) match -- tensor identity is checked
    separately via leaf_meta."""
    if isinstance(tree, dict):
        if "__t__" in tree:
            return {"__t__": "*"}
        if "__v__" in tree:
            return {"__v__": tree["__v__"]}
        if "__repr__" in tree:
            return {"__repr__": tree["__repr__"]}
        for tag in ("__d__", "__l__", "__tup__"):
            if tag in tree:
                inner = tree[tag]
                if isinstance(inner, dict):
                    return {tag: {k: _strip_tensor_keys(v)
                                  for k, v in inner.items()}}
                return {tag: [_strip_tensor_keys(v) for v in inner]}
    return tree


