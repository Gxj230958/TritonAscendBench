def _run_s2_pair(
    original_kernel: Path,
    severed_kernel: Path,
    entrypoint: str | None,
    shapes_doc: dict,
    shape_ids: list[str],
    seed: int,
    accel_disabled: bool,
    pinned_config: dict | None,
    interpret: bool,
) -> tuple[bool, str, dict | None, dict | None, str, Path]:
    """Spawn the original + severed subprocesses and strict-compare
    their manifests.

    The SAME real work runs for S2-smoke (``interpret=True``, CPU /
    ``TRITON_INTERPRET=1`` -- GPU-FREE, runs on THIS box) and
    S2-gpu-authoritative (``interpret=False``, needs CUDA). HOLE B:
    original side = the UNMODIFIED upstream ``original_kernel`` +
    ``entrypoint`` (the positional upstream callable, infer/ on path);
    severed side = the STAGED candidate ``severed_kernel`` (rewrite +
    synthesised ``run``). Returns
    ``(equivalent, reason, orig_status, sev_status, phase, out_dir)``
    where ``phase`` is a short failure tag for the caller's verdict
    string. ``orig_status``/``sev_status`` are None on a spawn that
    produced no status (the caller treats that as BLOCKED)."""
    import json
    import tempfile

    out_dir = Path(tempfile.mkdtemp(prefix="pa_s2_out_"))

    rc_o, st_o = _spawn_side(
        "original", original_kernel, shapes_doc, shape_ids, seed,
        out_dir, accel_disabled, pinned_config,
        entrypoint=entrypoint, interpret=interpret,
    )
    if rc_o != 0 or not st_o.get("ran"):
        return (
            False,
            f"original side did not run (rc={rc_o}): "
            f"{st_o.get('error') or st_o.get('_stderr', '')[:200]}",
            st_o, None, "original-no-run", out_dir,
        )

