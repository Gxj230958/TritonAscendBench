def register_shim_symbol(sc: SymbolClass) -> None:
    """Register a provably-inert Class-B symbol into `tasks/_frozen_shim/`.

    Default-deny: ONLY `CLASS_B_INERT_SHIM` with a non-empty proof is
    accepted. `tl`/`triton` re-exports (B-rewrite-public) are REJECTED
    -- they are rewritten to public imports, never shimmed. Class-A is
    REJECTED (raises ValueError -> the U1 contract's hard gate).
    """
    if sc.cls == CLASS_B_REWRITE_PUBLIC:
        raise ValueError(
            f"refusing to shim {sc.symbol!r}: B-rewrite-public symbols "
            f"(tl/triton re-exports) must be rewritten to public imports, "
            f"not shimmed"
        )
    if sc.cls != CLASS_B_INERT_SHIM:
        raise ValueError(
            f"refusing to shim {sc.symbol!r}: class {sc.cls!r} is not "
            f"B-inert-shim (only provably-inert Class-B may enter the shim)"
        )
    if not sc.proof:
        raise ValueError(
            f"refusing to shim {sc.symbol!r}: no proof string (B is "
            f"default-deny -- every shimmed symbol needs a recorded proof)"
        )
    _ensure_shim_package()


