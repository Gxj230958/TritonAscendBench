_MOE_ALIGN_STAGE2_BODY = '''

def _moe_align_block_size(
    topk_ids: torch.Tensor, num_experts: int, block_size: int,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Sort tokens by expert and pad each expert's run up to a multiple of
    block_size. Returns (sorted_token_ids, expert_ids per block,
    num_tokens_post_pad). Padding slots use sentinel = n_tokens."""
    flat = topk_ids.reshape(-1)
    n = flat.shape[0]
    order = torch.argsort(flat.to(torch.long), stable=True)
    sorted_e = flat[order].to(torch.long)
    sorted_tok, expert_ids, total = [], [], 0
    for e in range(num_experts):
        idx = order[sorted_e == e]
        cnt = idx.numel()
        pad = (-cnt) % block_size
        sorted_tok.append(idx.to(torch.int32))
        if pad:
            sorted_tok.append(torch.full((pad,), n, dtype=torch.int32,
                                         device=topk_ids.device))
        nblk = (cnt + pad) // block_size
        expert_ids.append(torch.full((nblk,), e, dtype=torch.int32,
                                     device=topk_ids.device))
        total += cnt + pad
    st = (torch.cat(sorted_tok) if sorted_tok
          else topk_ids.new_zeros(0, dtype=torch.int32))
    ei = (torch.cat(expert_ids) if expert_ids
          else topk_ids.new_zeros(0, dtype=torch.int32))
    return st, ei, torch.tensor([total], dtype=torch.int32,
                                device=topk_ids.device)


def run(inputs: dict) -> dict:
    st, ei, npp = _moe_align_block_size(
        inputs["topk_ids"], int(inputs["num_experts"]),
        int(inputs["block_size"]))
    return {"sorted_token_ids": st, "expert_ids": ei,
            "num_tokens_post_pad": npp}
'''

