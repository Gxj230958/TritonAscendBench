def _layer_norm_gated(
    x: torch.Tensor, g: torch.Tensor, w: torch.Tensor,
    b: torch.Tensor | None, residual: torch.Tensor | None, eps: float,
) -> torch.Tensor:
    """FLA/GDN gated norm: optional residual add → LayerNorm → SiLU gate."""
    xf = x.to(torch.float32)
    if residual is not None:
        xf = xf + residual.to(torch.float32)
    mean = xf.mean(-1, keepdim=True)
    var = xf.var(-1, keepdim=True, unbiased=False)
    y = (xf - mean) * torch.rsqrt(var + float(eps)) * w.to(torch.float32)
    if b is not None:
        y = y + b.to(torch.float32)
    y = y * F.silu(g.to(torch.float32))
    return y.to(x.dtype)


def run(inputs: dict) -> dict:
    return {"output": _layer_norm_gated(
        inputs["x"], inputs["g"], inputs["w"], inputs.get("b"),
        inputs.get("residual"), float(inputs.get("eps", 1e-5)))}
