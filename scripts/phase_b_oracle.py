_GROUPED_MLA_STAGE1_BODY = '''

def _rope_half(x: torch.Tensor) -> torch.Tensor:
    h = x.shape[-1] // 2
    return torch.cat([-x[..., h:], x[..., :h]], dim=-1)


def _grouped_mla_stage1(
    q: torch.Tensor, k_buffer: torch.Tensor, v_buffer: torch.Tensor,
    scale: float, cos: torch.Tensor | None = None,
    sin: torch.Tensor | None = None, rope_dim: int = 0,
) -> torch.Tensor:
    """DeepSeek MLA decode stage-1 attention scores+context.

    q: [n_tokens, H, D]; k_buffer/v_buffer: [n_ctx, D] shared across
    heads (MLA latent KV). When cos/sin given (USE_ROPE path, which this
    kernel's name `_fwd_grouped_kernel_stage1_rope` mandates), standard
    rotate_half RoPE is applied to the first `rope_dim` dims of q and the
    matching k columns before the dot product. Naive full-softmax ref.
    """
    qf = q.to(torch.float32)
    kf = k_buffer.to(torch.float32)
    vf = v_buffer.to(torch.float32)
    if cos is not None and sin is not None and rope_dim > 0:
        cf = cos.to(torch.float32)
        sf = sin.to(torch.float32)
        cf2 = torch.cat([cf, cf], dim=-1)
        sf2 = torch.cat([sf, sf], dim=-1)
        # q RoPE: cos/sin are indexed by the query token. k_buffer RoPE
        # needs cos/sin indexed by EACH cached context position — its
        # exact position mapping is contract-dependent (see ORACLE-SCOPE
        # downgrade). Only apply q-rope here; rotate k only when a
        # context-length-matched cos is supplied.
        if cf2.shape[0] == qf.shape[0]:
            qr = qf[..., :rope_dim]
            qf = torch.cat(
                [qr * cf2[:, None, :] + _rope_half(qr) * sf2[:, None, :],
                 qf[..., rope_dim:]], dim=-1)
        if cf2.shape[0] == kf.shape[0]:
            kr = kf[..., :rope_dim]
            kf = torch.cat(
                [kr * cf2 + _rope_half(kr) * sf2, kf[..., rope_dim:]], dim=-1)
    sc = torch.einsum("nhd,cd->nhc", qf, kf) * scale
    p = torch.softmax(sc, dim=-1)
    return torch.einsum("nhc,cd->nhd", p, vf).to(q.dtype)


def run(inputs: dict) -> dict:
    return {"output": _grouped_mla_stage1(
        inputs["q"], inputs["k_buffer"], inputs["v_buffer"],
        float(inputs["scale"]), inputs.get("cos"), inputs.get("sin"),
        int(inputs.get("rope_dim", 0)))}
'''

