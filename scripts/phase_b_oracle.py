def render_oracle(task_id: str, sig: KernelSig | None, meta: dict) -> tuple[str, str | None]:
    """Return (oracle_pytorch.py contents, new_oracle_tier or None)."""
    tier = meta.get("oracle_simplified", "upstream_oracle_required")
    cat = meta.get("category", "other")
    tolc = meta.get("tolerance_class", "elementwise")

    def _scope_suffix() -> str:
        if task_id in ORACLE_SCOPE_DOWNGRADE:
            return (f"\nORACLE-SCOPE (tier=upstream_oracle_required): "
                    f"{ORACLE_SCOPE_DOWNGRADE[task_id]}.\n")
        if task_id in ORACLE_SCOPE_NOTE:
            return f"\nORACLE-SCOPE: {ORACLE_SCOPE_NOTE[task_id]}.\n"
        return ""

    if task_id in WORKING_REFS:
        body, new_tier = WORKING_REFS[task_id]
        # Honest downgrade: if the kernel has an uncovered math path,
        # the canonical oracle is NOT exact — force upstream tier.
        if task_id in ORACLE_SCOPE_DOWNGRADE:
            new_tier = "upstream_oracle_required"
        header = _build_header(task_id, new_tier, tolc, cat, _scope_suffix())
        return header + body, new_tier

    kernel_fn = sig.fn_name if sig else meta.get("name", "<unknown>")
    tensor_inputs = sig.tensor_args if sig else []
    header = _build_header(task_id, tier, tolc, cat, _scope_suffix())
    stub = _STUB_BODY_TEMPLATE.format(
        task_id=task_id,
        kernel_fn=kernel_fn,
        tensor_inputs=tensor_inputs,
        tolerance_class=tolc,
    )
    return header + stub, None


def update_task(task_dir: Path, dry_run: bool) -> str:
    tid = task_dir.name
    meta_path = task_dir / "meta.yaml"
    meta = yaml.safe_load(meta_path.read_text())
    if tid in SKIP_TASKS:
        return "skip-poc"
    if meta.get("benchmark_version") != "0.1.0-frozen":
        return "skip-scaffold"

    kernel_name = meta.get("name", "")
    sig = _parse_kernel(task_dir / "kernel.py", kernel_name)
    text, new_tier = render_oracle(tid, sig, meta)

    if dry_run:
        return f"would-write (sig={'yes' if sig else 'no'}, new_tier={new_tier})"

    (task_dir / "oracle_pytorch.py").write_text(text)
    if new_tier and meta.get("oracle_simplified") != new_tier:
        meta["oracle_simplified"] = new_tier
        meta_path.write_text(yaml.safe_dump(meta, sort_keys=False, allow_unicode=True))
        return f"wrote oracle, tier→{new_tier}"
    return "wrote oracle"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--task", help="Only update one task id")
    args = ap.parse_args()

    counts: dict[str, int] = {}
    for level in ("level1", "level2", "level3"):
        for d in sorted((TASKS_ROOT / level).iterdir()):
            if not d.is_dir() or d.name.startswith("_"):
                continue
            if args.task and d.name != args.task:
                continue
            result = update_task(d, dry_run=args.dry_run)
            head = result.split(" ", 1)[0]
            counts[head] = counts.get(head, 0) + 1
            flag = {"wrote": "✓", "would-write": "·", "skip-poc": "·",
                    "skip-scaffold": "—"}.get(head, "?")
            print(f"  {flag} {d.name:55s} → {result}")

    print()
    print(f"== summary == {dict(counts)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
