def _silu_and_mul(x: torch.Tensor) -> torch.Tensor:
    """SwiGLU: split last dim in half, gate = silu(first), value = second."""
    half = x.shape[-1] // 2
    gate, up = x[..., :half], x[..., half:]
    return F.silu(gate.to(torch.float32)).to(x.dtype) * up


def run(inputs: dict) -> dict:
    return {"output": _silu_and_mul(inputs["x"])}
