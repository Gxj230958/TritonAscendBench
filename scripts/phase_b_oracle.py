_SOLVE_TRIL_BODY = '''

def _solve_tril(A: torch.Tensor) -> torch.Tensor:
    """Inverse of a unit/strictly-lower-triangular block (FLA chunk path).

    A: [..., T, T] lower-triangular. Returns the lower-triangular inverse
    so that A_inv @ A = I (forward substitution, fp32).
    """
    Af = A.to(torch.float32)
    T = Af.shape[-1]
    eye = torch.eye(T, device=A.device, dtype=torch.float32).expand_as(Af)
    inv = torch.linalg.solve_triangular(Af, eye, upper=False, unitriangular=False)
    return inv.to(A.dtype)


def run(inputs: dict) -> dict:
    return {"output": _solve_tril(inputs["A"])}
'''

_MERGE_16x16_BODY = '''

def _merge_16x16_to_32x32_inverse(A: torch.Tensor) -> torch.Tensor:
    """FLA chunk 16×16→32×32 lower-tri inverse merge.

    A is block-lower-triangular with two 16×16 diagonal blocks
    (A11, A22) and an off-diagonal A21. The 32×32 inverse is:
      [ A11^{-1}            0      ]
      [ -A22^{-1} A21 A11^{-1}  A22^{-1} ]
    """
    Af = A.to(torch.float32)
    *lead, n, _ = Af.shape
    h = n // 2
    A11 = Af[..., :h, :h]
    A21 = Af[..., h:, :h]
    A22 = Af[..., h:, h:]
    eye = torch.eye(h, device=A.device, dtype=torch.float32)
    i11 = torch.linalg.solve_triangular(A11, eye.expand_as(A11), upper=False)
    i22 = torch.linalg.solve_triangular(A22, eye.expand_as(A22), upper=False)
    out = torch.zeros_like(Af)
    out[..., :h, :h] = i11
    out[..., h:, h:] = i22
    out[..., h:, :h] = -i22 @ A21 @ i11
    return out.to(A.dtype)


def run(inputs: dict) -> dict:
    return {"output": _merge_16x16_to_32x32_inverse(inputs["A"])}
'''

