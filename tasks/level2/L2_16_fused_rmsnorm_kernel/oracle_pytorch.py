from __future__ import annotations

import torch
import torch.nn.functional as F


def _fused_rms(x: torch.Tensor, residual: torch.Tensor, weight: torch.Tensor, eps: float):
    """RMSNorm fused with a residual add: out = RMSNorm(x + residual)."""
    summed = x.to(torch.float32) + residual.to(torch.float32)
    inv = torch.rsqrt(summed.pow(2).mean(dim=-1, keepdim=True) + float(eps))
    norm = (summed * inv * weight.to(torch.float32)).to(x.dtype)
    return norm, summed.to(x.dtype)


