from __future__ import annotations

import torch
import torch.nn.functional as F


def _to_tf32(x: torch.Tensor) -> torch.Tensor:
    """Round fp32 to TF32 (drop low 13 mantissa bits), matching the kernel's
    unpinned tl.dot on TF32 cores."""
    return (x.contiguous().view(torch.int32) & ~((1 << 13) - 1)).view(torch.float32)


_AWQ_ORDER = [0, 4, 1, 5, 2, 6, 3, 7]


def _awq_unpack(packed: torch.Tensor) -> torch.Tensor:
    shifts = torch.tensor([o * 4 for o in _AWQ_ORDER],
                          device=packed.device, dtype=torch.int32)
    vals = (packed.to(torch.int32).unsqueeze(-1) >> shifts) & 0xF
    *lead, c, _ = vals.shape
    return vals.reshape(*lead, c * 8)


def _awq_gemm(
    a: torch.Tensor, qweight: torch.Tensor, scales: torch.Tensor,
    qzeros: torch.Tensor, group_size: int,
) -> torch.Tensor:
    """C = a @ dequant_awq(qweight). Dequant: (w4 - z4) * scale[group]
    with the public AWQ lane order; fp32 accumulate."""
    w = _awq_unpack(qweight).to(torch.float32)               # [K, N]
    z = _awq_unpack(qzeros).to(torch.float32)                # [K/g, N]
    Kdim = w.shape[0]
    grp = torch.arange(Kdim, device=w.device) // group_size
    b = (w - z[grp]) * scales.to(torch.float32)[grp]         # [K, N]
    return (_to_tf32(a.to(torch.float32)) @ _to_tf32(b)).to(a.dtype)


def run(inputs: dict) -> dict:
    qweight, qzeros = inputs["qweight"], inputs["qzeros"]
    # group_size: the kernel derives it from shapes, not a param it takes.
    group_size = qweight.shape[0] // qzeros.shape[0]
    return {
        "C": _awq_gemm(
            inputs["input"], qweight, inputs["scales"],
            qzeros, group_size,
        )
    }
