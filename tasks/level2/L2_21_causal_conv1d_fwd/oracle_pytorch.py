from __future__ import annotations

import torch
import torch.nn.functional as F


def _causal_conv1d_fwd(
    x: torch.Tensor, weight: torch.Tensor, bias: torch.Tensor | None,
    activation: str | None,
) -> torch.Tensor:
    """Depthwise causal 1-D conv (Mamba prefill).

    x: [dim, seqlen]; weight: [dim, KERNEL_WIDTH]. Left-pad by
    KERNEL_WIDTH-1 zeros so output[d,t] = sum_{j} x[d, t-K+1+j]·w[d,j]
    (+bias), optional SiLU. Returns [dim, seqlen].
    """
    dim, seqlen = x.shape
    kw = weight.shape[-1]
    xf = x.to(torch.float32).unsqueeze(0)                   # [1, dim, L]
    wf = weight.to(torch.float32).unsqueeze(1)              # [dim, 1, kw]
    xp = F.pad(xf, (kw - 1, 0))
    y = F.conv1d(xp, wf, groups=dim).squeeze(0)             # [dim, L]
    if bias is not None:
        y = y + bias.to(torch.float32).unsqueeze(-1)
    if activation in ("silu", "swish"):
        y = F.silu(y)
    return y.to(x.dtype)


def run(inputs: dict) -> dict:
    return {
        "output": _causal_conv1d_fwd(
            inputs["x"], inputs["weight"], inputs.get("bias"),
            inputs.get("activation"),
        )
    }
