from __future__ import annotations

import torch
import torch.nn.functional as F


def _pack_bitmatrix(topk_ids: torch.Tensor, num_experts: int) -> torch.Tensor:
    """Pack a [n_tokens, n_experts] expert-selection matrix into int32
    bitwords (bit e set ⇒ token routed to expert e). Returns
    [n_tokens, ceil(num_experts/32)] int32."""
    n = topk_ids.shape[0]
    nw = (num_experts + 31) // 32
    out = torch.zeros(n, nw, dtype=torch.int32, device=topk_ids.device)
    for t in range(n):
        for e in topk_ids[t].reshape(-1).tolist():
            e = int(e)
            if 0 <= e < num_experts:
                out[t, e // 32] |= (1 << (e % 32))
    return out


def run(inputs: dict) -> dict:
    return {"bitmatrix": _pack_bitmatrix(
        inputs["topk_ids"], int(inputs["num_experts"]))}
