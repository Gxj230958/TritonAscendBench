"""Oracle reference for L2_11_rejection_sample_kernel.

Tier: formula_exact_manual
Tolerance class: sampling_rng
Category: sampling

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).
"""
from __future__ import annotations

import torch
import torch.nn.functional as F


def _rejection_sample(
    draft_token_ids: torch.Tensor,     # [n_tokens] proposed tokens (flattened)
    cu_num_draft_tokens: torch.Tensor, # [n_reqs] cumulative draft lengths
    draft_probs: torch.Tensor,         # [n_tokens, vocab] q(x)
    target_probs: torch.Tensor,        # [n_tokens, vocab] p(x)
    bonus_token_ids: torch.Tensor,     # [n_reqs] extra token if all accepted
    recovered_token_ids: torch.Tensor, # [n_tokens] residual-dist samples
    uniform_probs: torch.Tensor,       # [n_tokens] U(0,1) draws (INPUT → det.)
    is_greedy: torch.Tensor,           # [n_reqs] bool
    max_spec_len: int,
) -> torch.Tensor:
    """Random-sampling rejection sampler (deterministic given uniforms).

    This is the reference for the *random* speculative-decode kernel
    (`rejection_random_sample_kernel`), which processes only the
    non-greedy requests. Greedy requests are handled by a separate
    greedy kernel upstream, so this kernel early-exits on a greedy
    request and leaves its row at the -1 sentinel. The reference mirrors
    that contract: greedy rows stay all -1.

    For a non-greedy request, accept draft token x while
    `q(x) > 0 and p(x)/q(x) >= U` (matching the kernel's acceptance test
    exactly, including reject-when-q<=0). On the first rejection emit the
    pre-computed recovered (residual-distribution) token and stop the
    chain; if every draft token is accepted, append the bonus token.
    Output is a [n_reqs, max_spec_len + 1] id matrix padded with -1.
    """
    n_reqs = cu_num_draft_tokens.shape[0]
    # int32 to match the kernel's output_token_ids dtype (bit-exact compare
    # rejects an int64-vs-int32 mismatch even when the values are identical).
    out = torch.full(
        (n_reqs, max_spec_len + 1), -1,
        dtype=torch.int32, device=draft_token_ids.device,
    )
    starts = torch.cat([
        cu_num_draft_tokens.new_zeros(1), cu_num_draft_tokens[:-1]
    ]).to(torch.long)
    for r in range(n_reqs):
        if bool(is_greedy[r].item()):
            # Greedy requests are skipped by the random kernel (early
            # exit); the row keeps its -1 sentinel padding.
            continue
        s = int(starts[r].item())
        e = int(cu_num_draft_tokens[r].item())
        n = e - s
        col = 0
        rejected = False
        for i in range(n):
            tok = int(draft_token_ids[s + i].item())
            p = float(target_probs[s + i, tok].item())
            q = float(draft_probs[s + i, tok].item())
            # Kernel accept test: draft_prob > 0 and p/q >= U.
            accept = q > 0.0 and (p / q) >= float(uniform_probs[s + i].item())
            if accept:
                out[r, col] = tok
                col += 1
            else:
                out[r, col] = int(recovered_token_ids[s + i].item())
                col += 1
                rejected = True
                break
        if not rejected:
            out[r, col] = int(bonus_token_ids[r].item())
    return out


def run(inputs: dict) -> dict:
    return {
        "output_token_ids": _rejection_sample(
            inputs["draft_token_ids"], inputs["cu_num_draft_tokens"],
            inputs["draft_probs"], inputs["target_probs"],
            inputs["bonus_token_ids"], inputs["recovered_token_ids"],
            inputs["uniform_probs"], inputs["is_greedy"],
            int(inputs["max_spec_len"]),
        )
    }
