import torch
import torch.nn.functional as F


def _post_reorder_cutlass_moe(
    down_output: torch.Tensor, src2dst: torch.Tensor,
    topk_weights: torch.Tensor, topk: int,
) -> torch.Tensor:
    """Scatter-combine cutlass grouped-GEMM output back to token order
    with topk weighting."""
    n = topk_weights.shape[0]
    s2d = src2dst.to(torch.long).reshape(n, topk)
    w = topk_weights.to(torch.float32)
    out = down_output.new_zeros((n, *down_output.shape[1:]), dtype=torch.float32)
    for j in range(topk):
        out += down_output[s2d[:, j]].to(torch.float32) * w[:, j:j + 1]
    return out.to(down_output.dtype)


