import torch
import torch.nn.functional as F


def _w8a8_block_scaled_mm(
    A: torch.Tensor, B: torch.Tensor, As: torch.Tensor, Bs: torch.Tensor,
    group_n: int, group_k: int,
) -> torch.Tensor:
    """Block-scaled INT8 GEMM (vLLM W8A8 path).

    A: [M, K] int8; B: [K, N] int8.
    As: [M, ceil(K/group_k)] fp32 per-(row, k-block) activation scale.
    Bs: [ceil(K/group_k), ceil(N/group_n)] fp32 per-(k-block, n-block).
    C[m,n] = sum_k A[m,k]·B[k,n]·As[m, k//gk]·Bs[k//gk, n//gn], fp32 acc.
    """
    M, K = A.shape
    _, N = B.shape
    Af = A.to(torch.float32)
    Bf = B.to(torch.float32)
    k_idx = (torch.arange(K, device=A.device) // group_k)
    n_idx = (torch.arange(N, device=A.device) // group_n)
    # Expand block scales to full [M,K] / [K,N].
    As_full = As.to(torch.float32)[:, k_idx]                 # [M, K]
    Bs_full = Bs.to(torch.float32)[k_idx][:, n_idx]          # [K, N]
    A_deq = Af * As_full
    B_deq = Bf * Bs_full
    return (A_deq @ B_deq)


