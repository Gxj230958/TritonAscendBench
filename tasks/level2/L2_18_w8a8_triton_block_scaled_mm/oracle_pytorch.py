"""Oracle reference for L2_18_w8a8_triton_block_scaled_mm.

Tier: formula_exact_manual
Tolerance class: vector_reduce

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).

The graded kernel is the vLLM host wrapper
``kernel.py::w8a8_triton_block_scaled_mm`` which launches the
``@triton.jit`` ``_w8a8_triton_block_scaled_mm`` cube kernel. Its
contract (read directly from the wrapper / jit body):

- ``A``: [M, K] int8 activation, row-major contiguous.
- ``B``: [N, K] int8 weight (the jit reads ``N, K = B.shape`` and uses
  ``stride_bk = B.stride(1)`` / ``stride_bn = B.stride(0)``, i.e. it
  contracts over K and indexes rows by N -> the GEMM is ``A @ B.T``).
- ``As``: [M, ceil(K/block_k)] fp32 per-(row, k-block) activation scale.
- ``Bs``: [ceil(N/block_n), ceil(K/block_k)] fp32 per-(n-block, k-block)
  weight scale.
- ``block_size``: [block_n, block_k].

C[m,n] = sum_k A[m,k]·B[n,k]·As[m, k//bk]·Bs[n//bn, k//bk], fp32 acc,
cast once to ``output_dtype`` (fp16 default) at the end -- mirroring the
jit accumulator, which is fp32 and casts only at the final store.
"""
from __future__ import annotations

import torch


def _expand_scale_a(As: torch.Tensor, block_k: int, K: int) -> torch.Tensor:
    """As [M, ceil(K/block_k)] -> [M, K], each k-block scale repeated block_k."""
    expanded = As.repeat_interleave(block_k, dim=-1)
    return expanded[:, :K]


def _expand_scale_b(
    Bs: torch.Tensor, block_n: int, block_k: int, N: int, K: int
) -> torch.Tensor:
    """Bs [ceil(N/block_n), ceil(K/block_k)] -> [N, K]."""
    expanded = Bs.repeat_interleave(block_k, dim=-1).repeat_interleave(block_n, dim=0)
    return expanded[:N, :K]


def _w8a8_block_scaled_mm(
    A: torch.Tensor,
    B: torch.Tensor,
    As: torch.Tensor,
    Bs: torch.Tensor,
    block_size: list[int],
    output_dtype: torch.dtype = torch.float16,
) -> torch.Tensor:
    """Block-scaled INT8 GEMM (vLLM W8A8 path); see module docstring."""
    block_n, block_k = int(block_size[0]), int(block_size[1])
    N, K = B.shape
    M = A.numel() // A.shape[-1]
    A_2d = A.reshape(M, K)
    As_2d = As.reshape(M, As.shape[-1])

    A_scale = _expand_scale_a(As_2d.to(torch.float32), block_k, K)
    B_scale = _expand_scale_b(Bs.to(torch.float32), block_n, block_k, N, K)

    A_fp = A_2d.to(torch.float32) * A_scale
    B_fp = B.to(torch.float32) * B_scale

    C = A_fp @ B_fp.T
    C = C.to(output_dtype)

    out_shape = A.shape[:-1] + (N,)
    return C.reshape(out_shape)


def run(inputs: dict) -> dict:
    return {
        "C": _w8a8_block_scaled_mm(
            inputs["A"],
            inputs["B"],
            inputs["As"],
            inputs["Bs"],
            inputs["block_size"],
            inputs.get("output_dtype", torch.float16),
        )
    }
