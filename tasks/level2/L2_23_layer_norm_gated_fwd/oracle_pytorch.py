from __future__ import annotations

import torch


def _silu(t: torch.Tensor) -> torch.Tensor:
    """SiLU spelled from its definition x * sigmoid(x) = x / (1 + exp(-x)) --
    keeps the oracle body free of high-level torch ops (contract §6 / L195)."""
    return t / (1.0 + torch.exp(-t))


def _layer_norm_gated(
    x: torch.Tensor, g: torch.Tensor, w: torch.Tensor,
    b: torch.Tensor | None, residual: torch.Tensor | None, eps: float,
    is_rms_norm: bool,
) -> torch.Tensor:
    """FLA/GDN gated norm: optional residual add → (RMS|Layer)Norm → SiLU gate.

    Mirrors ``layer_norm_gated_fwd_kernel``. With ``is_rms_norm`` the kernel
    takes the IS_RMS_NORM=True branch: normalise by ``rsqrt(mean(x^2)+eps)``
    with NO mean subtraction (var here is the mean of squares, not the
    mean-removed variance). Otherwise it is the standard mean-centred
    LayerNorm branch. Both branches then scale by ``w``, add ``b``, and gate
    with the SiLU output gate (ACTIVATION="swish").
    """
    xf = x.to(torch.float32)
    if residual is not None:
        xf = xf + residual.to(torch.float32)
    if is_rms_norm:
        # RMS branch: var = sum(x^2)/D, no mean subtraction.
        var = xf.pow(2).mean(-1, keepdim=True)
        x_hat = xf * torch.rsqrt(var + float(eps))
    else:
        mean = xf.mean(-1, keepdim=True)
        var = xf.var(-1, keepdim=True, unbiased=False)
        x_hat = (xf - mean) * torch.rsqrt(var + float(eps))
    y = x_hat * w.to(torch.float32)
    if b is not None:
        y = y + b.to(torch.float32)
    y = y * _silu(g.to(torch.float32))
    return y.to(x.dtype)


def run(inputs: dict) -> dict:
    return {"output": _layer_norm_gated(
        inputs["x"], inputs["g"], inputs["weight"], inputs.get("bias"),
        inputs.get("residual"), float(inputs.get("eps", 1e-5)),
        bool(inputs.get("is_rms_norm", False)))}
