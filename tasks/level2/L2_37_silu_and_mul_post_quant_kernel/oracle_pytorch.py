from __future__ import annotations

import torch


def _silu(t: torch.Tensor) -> torch.Tensor:
    """SiLU spelled from its definition x * sigmoid(x) = x / (1 + exp(-x)) --
    keeps the oracle body free of high-level torch ops (contract §6 / L195)."""
    return t / (1.0 + torch.exp(-t))


def _silu_and_mul_post_quant(
    x: torch.Tensor, masked_m: torch.Tensor, quant_group_size: int,
    fp8_max: float = 448.0,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Masked SiLU+mul followed by per-group FP8 quant.

    x: [E, T, 2D] (gate|up per expert/token). masked_m: [E] valid token
    count. Computes y = silu(gate)·up for valid tokens, then per-group
    (quant_group_size along D) symmetric FP8 quant. Invalid tokens are
    zeroed. Returns (y_q float8_e4m3fn [E,T,D], y_s fp32 [E,T,D/g]).
    """
    E, T, two_d = x.shape
    d = two_d // 2
    gate, up = x[..., :d], x[..., d:]
    y = (_silu(gate.to(torch.float32)) * up.to(torch.float32))     # [E,T,D]
    tok = torch.arange(T, device=x.device).view(1, T)
    valid = tok < masked_m.to(torch.long).view(E, 1)
    y = y * valid.unsqueeze(-1)
    g = quant_group_size
    yv = y.reshape(E, T, d // g, g)
    s = (yv.abs().amax(dim=-1, keepdim=True) / float(fp8_max)).clamp_min(1e-12)
    yq = (yv / s).clamp(-float(fp8_max), float(fp8_max))
    yq = yq.reshape(E, T, d).to(torch.float8_e4m3fn)
    return yq, s.squeeze(-1).reshape(E, T, d // g)


def run(inputs: dict) -> dict:
    yq, ys = _silu_and_mul_post_quant(
        inputs["input"], inputs["masked_m"],
        int(inputs["quant_group_size"]), float(inputs.get("fp8_max", 448.0)),
    )
    return {"output": yq, "output_scale": ys}
