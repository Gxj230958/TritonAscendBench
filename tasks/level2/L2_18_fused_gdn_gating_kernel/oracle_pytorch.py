from __future__ import annotations

import torch
import torch.nn.functional as F


def _fused_gdn_gating(
    A_log: torch.Tensor, a: torch.Tensor, dt_bias: torch.Tensor,
    beta: float = 1.0, threshold: float = 20.0,
) -> torch.Tensor:
    """GDN gating: g = -exp(A_log) · softplus(a + dt_bias) (β-scaled)."""
    sp = F.softplus(beta * (a.to(torch.float32) + dt_bias.to(torch.float32)),
                     beta=1.0, threshold=threshold) / beta
    return (-torch.exp(A_log.to(torch.float32)) * sp).to(a.dtype)


