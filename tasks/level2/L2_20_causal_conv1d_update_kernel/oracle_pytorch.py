from __future__ import annotations

import torch
import torch.nn.functional as F


def _causal_conv1d_update(
    x: torch.Tensor, conv_state: torch.Tensor, weight: torch.Tensor,
    bias: torch.Tensor | None, activation: str | None,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Single-step decode causal conv1d state update.

    x: [batch, dim] new token; conv_state: [batch, dim, state_len]
    rolling window; weight: [dim, KERNEL_WIDTH] (state_len == KW).
    Roll the window left, append x, conv = sum(window·weight)+bias,
    optional SiLU. Returns (output [batch,dim], new_conv_state).
    """
    new_state = torch.roll(conv_state.to(torch.float32), shifts=-1, dims=-1)
    new_state[..., -1] = x.to(torch.float32)
    w = weight.to(torch.float32).unsqueeze(0)               # [1, dim, KW]
    y = (new_state * w).sum(dim=-1)                          # [batch, dim]
    if bias is not None:
        y = y + bias.to(torch.float32)
    if activation in ("silu", "swish"):
        y = F.silu(y)
    return y.to(x.dtype), new_state.to(conv_state.dtype)


def run(inputs: dict) -> dict:
    y, st = _causal_conv1d_update(
        inputs["x"], inputs["conv_state"], inputs["weight"],
        inputs.get("bias"), inputs.get("activation"),
    )
    return {"output": y, "conv_state": st}
