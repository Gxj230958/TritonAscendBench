from __future__ import annotations

import torch
import torch.nn.functional as F


def _fused_dual_residual_rms(
    x: torch.Tensor, residual_a: torch.Tensor, residual_b: torch.Tensor,
    weight: torch.Tensor, eps: float,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Pre-RMSNorm sum of two residuals, then RMSNorm.

    Common pre-attention pattern: hidden = hidden + residual_a + residual_b;
    norm = RMSNorm(hidden); returns (norm, hidden_for_next_residual).
    """
    summed = x.to(torch.float32) + residual_a.to(torch.float32) + residual_b.to(torch.float32)
    inv = torch.rsqrt(summed.pow(2).mean(dim=-1, keepdim=True) + float(eps))
    norm = (summed * inv * weight.to(torch.float32)).to(x.dtype)
    return norm, summed.to(x.dtype)


def run(inputs: dict) -> dict:
    norm, summed = _fused_dual_residual_rms(
        inputs["x"], inputs["residual_a"], inputs["residual_b"],
        inputs["weight"], float(inputs.get("eps", 1e-6)),
    )
    return {"output": norm, "hidden": summed}
