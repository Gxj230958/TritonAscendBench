"""Oracle reference for L2_06_qkv_lora_b_kernel.

Tier: formula_exact_manual
Tolerance class: attention_flash
Category: attention

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).

Fused QKV LoRA-B expand (segmented SGMV). The kernel packs three sgemms
(q/k/v) into a single launch and accumulates each into a disjoint output
column window:

    x:           (s, n_slices * r)              n_slices = 3 (Q/K/V slices)
    qkv_lora_b:  (num_lora, output_dim, r)      output_dim = sum of slice dims
    output:      (s, output_dim)

For segment ``b`` (rows ``seg_indptr[b] : seg_indptr[b+1]``) with adapter
``w = weight_indices[b]``, rank ``rank = lora_ranks[w]``, scaling
``scalings[w]`` and clamped ``K = min(r, rank)``, each slice ``j`` reads x
columns ``[j*K : j*K + K]`` (the clamped-K stride, matching the kernel's
``qkv_id * K`` offset after ``K = min(K, rank)``) and writes the output
window ``[output_offset[j] : output_offset[j+1]]`` with

    out[rows, n_start:n_end] += scaling * (x[rows, j*K:j*K+K]
                                           @ qkv_lora_b[w, n_start:n_end, :K].T)

A rank-0 (or empty) segment is a no-op (PyTorch (m,0)@(0,n) == 0).
"""
from __future__ import annotations

import torch


def _qkv_lora_b(
    x: torch.Tensor,
    qkv_lora_b: torch.Tensor,
    seg_indptr: torch.Tensor,
    weight_indices: torch.Tensor,
    lora_ranks: torch.Tensor,
    scalings: torch.Tensor,
    base_output: torch.Tensor | None,
    n_slices: int = 3,
) -> torch.Tensor:
    """Fused QKV LoRA-B expand (segmented SGMV), three disjoint output slices."""
    s = x.shape[0]
    r = qkv_lora_b.shape[-1]
    output_dim = qkv_lora_b.shape[-2]
    if output_dim % n_slices != 0:
        raise ValueError(
            f"output_dim {output_dim} not divisible by n_slices {n_slices}")
    per_slice = output_dim // n_slices
    n_offs = [j * per_slice for j in range(n_slices + 1)]

    out = (base_output.to(torch.float32).clone()
           if base_output is not None
           else x.new_zeros((s, output_dim), dtype=torch.float32))

    seg = seg_indptr.to(torch.long).tolist()
    xf = x.to(torch.float32)
    wf = qkv_lora_b.to(torch.float32)
    for b in range(len(seg) - 1):
        start, end = seg[b], seg[b + 1]
        if end <= start:
            continue
        w = int(weight_indices[b].item())
        rank = int(lora_ranks[w].item())
        if rank <= 0:
            continue
        k = min(r, rank)
        scaling = float(scalings[w].item())
        for j in range(n_slices):
            n_start, n_end = n_offs[j], n_offs[j + 1]
            x_slice = xf[start:end, j * k: j * k + k]          # [seg_len, K]
            w_slice = wf[w, n_start:n_end, :k]                 # [n_size, K]
            out[start:end, n_start:n_end] += scaling * (x_slice @ w_slice.T)
    return out.to(x.dtype)


def run(inputs: dict) -> dict:
    return {"output": _qkv_lora_b(
        inputs["x"], inputs["qkv_lora_b"], inputs["seg_indptr"],
        inputs["weight_indices"], inputs["lora_ranks"],
        inputs["scalings"], inputs.get("base_output"))}
