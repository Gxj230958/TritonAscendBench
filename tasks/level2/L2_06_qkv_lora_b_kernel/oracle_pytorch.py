from __future__ import annotations

import torch
import torch.nn.functional as F


def _qkv_lora_b(
    x: torch.Tensor, weights: torch.Tensor, seg_indptr: torch.Tensor,
    weight_indices: torch.Tensor, lora_ranks: torch.Tensor,
    scalings: torch.Tensor, base_output: torch.Tensor | None,
) -> torch.Tensor:
    """QKV LoRA-B expand (segmented SGMV) — same math as gate/up LoRA-B."""
    n = x.shape[0]
    od = weights.shape[1]
    out = (base_output.to(torch.float32).clone()
           if base_output is not None
           else x.new_zeros((n, od), dtype=torch.float32))
    seg = seg_indptr.to(torch.long).tolist()
    xf = x.to(torch.float32); wf = weights.to(torch.float32)
    for i in range(len(seg) - 1):
        s, e = seg[i], seg[i + 1]
        if e <= s:
            continue
        ad = int(weight_indices[i].item())
        r = int(lora_ranks[ad].item())
        out[s:e] += float(scalings[ad].item()) * (xf[s:e, :r] @ wf[ad, :, :r].T)
    return out.to(x.dtype)


