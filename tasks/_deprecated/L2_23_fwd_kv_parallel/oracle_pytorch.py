from __future__ import annotations

import torch
import torch.nn.functional as F


def _lightning_kv(
    q: torch.Tensor, k: torch.Tensor, v: torch.Tensor,
    slope: torch.Tensor,
) -> torch.Tensor:
    """Lightning-attention prefill (decay-weighted linear attention).

    q,k,v: [B, H, L, D]. o[t] = sum_{s<=t} decay^{t-s} (q_t·k_s) v_s,
    decay = exp(-slope). Naive O(L^2) reference (the kernel does a
    chunked KV-parallel + reduce; same result).
    """
    qf = q.to(torch.float32); kf = k.to(torch.float32); vf = v.to(torch.float32)
    B, H, L, D = qf.shape
    sc = torch.einsum("bhld,bhsd->bhls", qf, kf)            # [B,H,L,L]
    t = torch.arange(L, device=q.device)
    dist = (t[:, None] - t[None, :]).clamp_min(0).to(torch.float32)
    sl = slope.to(torch.float32).reshape(1, H, 1, 1)
    mask = (t[:, None] >= t[None, :]).to(torch.float32)
    decay = torch.exp(-sl * dist) * mask
    return torch.einsum("bhls,bhsd->bhld", sc * decay, vf).to(q.dtype)


def run(inputs: dict) -> dict:
    return {"output": _lightning_kv(
        inputs["q"], inputs["k"], inputs["v"], inputs["slope"])}
