"""Oracle reference for L3_01_kernel_unified_attention_3d.

Tier: upstream_oracle_required
Tolerance class: attention_flash
Category: attention

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).
ORACLE-SCOPE (tier=upstream_oracle_required): covers causal + GQA + ALiBi + softcap; NOT covered: USE_SINKS, USE_FP8/KV_QUANT_MODE, USE_QQ_BIAS, USE_MM_PREFIX.

"""
from __future__ import annotations

import torch
import torch.nn.functional as F


def _unified_attention(
    q: torch.Tensor, k: torch.Tensor, v: torch.Tensor,
    cu_seqlens_q: torch.Tensor, seqused_k: torch.Tensor,
    scale: float, causal: bool = True,
    alibi_slopes: torch.Tensor | None = None,
    softcap: float = 0.0,
) -> torch.Tensor:
    """Varlen flash attention (vLLM unified). q/k/v packed [total, H, D]
    with per-sequence ranges from cu_seqlens_q; seqused_k gives valid KV
    length. Causal SDPA in fp32, GQA-broadcast if H_q != H_kv.

    Covered optional paths: USE_ALIBI_SLOPES (additive linear bias),
    USE_SOFTCAP (logit tanh soft-cap). NOT covered (→ tier downgraded,
    see ORACLE-SCOPE in module docstring): USE_SINKS, USE_FP8 /
    KV_QUANT_MODE, USE_QQ_BIAS, USE_MM_PREFIX. A solution exercising
    those configs must be graded against the upstream oracle, not this.
    """
    cu = cu_seqlens_q.to(torch.long).tolist()
    Hq, D = q.shape[1], q.shape[2]
    Hk = k.shape[1]
    g = Hq // Hk
    out = q.new_zeros(q.shape, dtype=torch.float32)
    qf, kf, vf = q.to(torch.float32), k.to(torch.float32), v.to(torch.float32)
    for i in range(len(cu) - 1):
        s, e = cu[i], cu[i + 1]
        Lq = e - s
        Lk = int(seqused_k[i].item())
        for h in range(Hq):
            hk = h // g
            sc = (qf[s:e, h] @ kf[s:s + Lk, hk].T) * scale     # [Lq,Lk]
            if softcap and softcap > 0:
                c = float(softcap)
                sc = c * torch.tanh(sc / c)
            if alibi_slopes is not None:
                qi = torch.arange(Lq, device=q.device)[:, None] + (Lk - Lq)
                ki = torch.arange(Lk, device=q.device)[None, :]
                sc = sc - float(alibi_slopes[h].item()) * (qi - ki).to(torch.float32)
            if causal:
                qi = torch.arange(Lq, device=q.device)[:, None] + (Lk - Lq)
                ki = torch.arange(Lk, device=q.device)[None, :]
                sc = sc.masked_fill(ki > qi, float("-inf"))
            p = torch.softmax(sc, dim=-1)
            out[s:e, h] = p @ vf[s:s + Lk, hk]
    return out.to(q.dtype)


def run(inputs: dict) -> dict:
    return {"output": _unified_attention(
        inputs["q"], inputs["k"], inputs["v"], inputs["cu_seqlens_q"],
        inputs["seqused_k"], float(inputs["scale"]),
        bool(inputs.get("causal", True)),
        inputs.get("alibi_slopes"), float(inputs.get("softcap", 0.0)))}
