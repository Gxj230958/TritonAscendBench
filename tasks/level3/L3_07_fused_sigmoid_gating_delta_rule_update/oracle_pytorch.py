from __future__ import annotations

import torch


def _softplus(x: torch.Tensor, beta: float, threshold: float) -> torch.Tensor:
    """softplus(x; beta, threshold) spelled from its definition -- keeps the
    oracle body free of high-level torch ops (contract §6 / L195).

    softplus(x) = (1/beta) * log(1 + exp(beta*x)); to avoid exp overflow it is
    evaluated as relu(z) + log1p(exp(-|z|)) with z = beta*x, then divided by
    beta. Matching F.softplus, inputs with beta*x > threshold fall back to the
    linear branch (returns x) so large activations stay numerically stable.
    """
    z = beta * x
    relu_z = torch.clamp_min(z, 0.0)
    stable = (relu_z + torch.log1p(torch.exp(-torch.abs(z)))) / beta
    return torch.where(z > threshold, x, stable)


def _fused_sigmoid_gating_delta_update(
    A_log: torch.Tensor, a: torch.Tensor, dt_bias: torch.Tensor,
    q: torch.Tensor, k: torch.Tensor, v: torch.Tensor,
    beta: torch.Tensor, state: torch.Tensor, softplus_beta: float = 1.0,
    softplus_threshold: float = 20.0,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Gated DeltaNet single-step update.

    g = exp(-exp(A_log)·softplus(a+dt_bias)); Sg = g·state;
    state' = Sg + β·k^T(v − k·Sg); out = q·state'. The kS contraction reads
    the DECAYED state Sg (gate applied before the delta correction).
    q,k,v: [B,H,D]; state: [B,H,D,D].
    """
    sp = _softplus(a.to(torch.float32) + dt_bias.to(torch.float32),
                   softplus_beta, softplus_threshold)
    g = torch.exp(-torch.exp(A_log.to(torch.float32)) * sp)   # [B,H]
    g = g.reshape(*g.shape, 1, 1)
    qf, kf, vf = (t.to(torch.float32) for t in (q, k, v))
    # Gate the state BEFORE the delta correction (gated DeltaNet: the kS
    # contraction reads the decayed state g*S, not the raw S). This matches
    # the frozen upstream triton kernel (b_h *= exp(b_g) precedes
    # b_v -= sum(b_h*b_k)) and the Ascend NPU reference (state Muls by the
    # decay precedes the state*k contraction).
    S = g * state.to(torch.float32)
    kS = torch.einsum("bhd,bhde->bhe", kf, S)
    delta = (vf - kS) * beta.to(torch.float32).reshape(*beta.shape, 1)
    S = S + torch.einsum("bhd,bhe->bhde", kf, delta)
    out = torch.einsum("bhd,bhde->bhe", qf, S)
    return out.to(q.dtype), S.to(state.dtype)


def run(inputs: dict) -> dict:
    o, s = _fused_sigmoid_gating_delta_update(
        inputs["A_log"], inputs["a"], inputs["dt_bias"],
        inputs["q"], inputs["k"], inputs["v"], inputs["beta"],
        inputs["state"], float(inputs.get("softplus_beta", 1.0)),
        float(inputs.get("softplus_threshold", 20.0)))
    return {"output": o, "state": s}
