from __future__ import annotations

import torch


def _chunk_cumsum(chunk: torch.Tensor, reverse: bool) -> torch.Tensor:
    """Cumulative sum along axis 0 of one chunk (suffix sum when reverse)."""
    if reverse:
        return torch.flip(torch.cumsum(torch.flip(chunk, [0]), dim=0), [0])
    return torch.cumsum(chunk, dim=0)


def _chunk_local_cumsum_vector_varlen(
    g: torch.Tensor,
    chunk_size: int,
    cu_seqlens: torch.Tensor,
    reverse: bool,
) -> torch.Tensor:
    """Variable-length per-chunk local cumulative sum (FLA varlen path).

    Mirrors ``chunk_local_cumsum_vector_kernel`` (kernel.py:98) when
    ``cu_seqlens is not None`` -> ``IS_VARLEN=True``, with the standard
    packed varlen layout (``head_first=False``, single batch ``B == 1``):

        g: ``[1, total_T, H, S]`` -- ``total_T`` packed tokens.
        cu_seqlens: ``[0, l1, l1+l2, ..., total_T]`` int indptr; segment
            ``n`` spans tokens ``[cu_seqlens[n], cu_seqlens[n+1])``.

    Within each segment the cumsum **resets at every ``chunk_size``
    boundary measured from the segment start** (``prepare_chunk_indices``
    emits ``cdiv(len_n, BT)`` chunks per segment), and the last chunk of a
    segment may be partial (``len_n`` need not be a multiple of ``BT``).
    The kernel zero-pads the ragged tail via ``boundary_check`` before the
    triangular ``tl.dot`` and stores only the valid rows, so the result on
    the valid rows is exactly the segment-local per-chunk cumsum below.

    Args:
        g: ``[1, total_T, H, S]`` rank-4 packed tensor.
        chunk_size: BT block size (power of 2, >= 16).
        cu_seqlens: 1-D int segment indptr; ``cu_seqlens[-1] == total_T``.
        reverse: suffix cumsum within each chunk.

    Returns:
        ``[1, total_T, H, S]`` with the per-chunk local cumsum.
    """
    gf = g.to(torch.float32)
    if gf.shape[0] != 1:
        raise ValueError(
            "chunk_local_cumsum_vector varlen oracle: batch dim must be 1 "
            f"(packed varlen layout), got g.shape[0]={gf.shape[0]}"
        )
    BT = chunk_size
    cu = cu_seqlens.to(torch.long).tolist()
    total_T = gf.shape[1]
    if cu[-1] != total_T:
        raise ValueError(
            f"chunk_local_cumsum_vector varlen oracle: cu_seqlens[-1]={cu[-1]} "
            f"must equal the packed token dim total_T={total_T}"
        )
    out = torch.empty_like(gf)
    for n in range(len(cu) - 1):
        a, b = cu[n], cu[n + 1]
        if b <= a:  # zero-length segment: prepare_chunk_indices emits no rows
            continue
        seg = gf[0, a:b]  # [len_n, H, S]
        len_n = b - a
        for lo in range(0, len_n, BT):
            hi = min(lo + BT, len_n)
            out[0, a + lo:a + hi] = _chunk_cumsum(seg[lo:hi], reverse)
    return out.to(g.dtype)


def _chunk_local_cumsum_vector_fixed(
    g: torch.Tensor,
    chunk_size: int,
    reverse: bool,
    head_first: bool,
) -> torch.Tensor:
    """Fixed-length per-chunk local cumulative sum (``cu_seqlens is None``).

    Matches ``chunk_local_cumsum_vector_kernel`` on the non-varlen path:
    cumsum resets at every ``chunk_size`` boundary. For ``T = NT * BT``,

        out[..., t * BT + k, :] = sum_{i=0..k} g[..., t * BT + i, :]

    Equivalent to ``g.view(B, H, NT, BT, -1).cumsum(-2).view(B, H, T, -1)``.
    """
    gf = g.to(torch.float32)
    if head_first:
        B, H, T, S = gf.shape
    else:
        B, T, H, S = gf.shape
        gf = gf.transpose(1, 2).contiguous()  # -> (B, H, T, S)
    BT = chunk_size
    if T % BT != 0:
        raise ValueError(
            f"chunk_local_cumsum_vector oracle: T={T} must be a "
            f"multiple of chunk_size={BT}"
        )
    NT = T // BT
    chunked = gf.view(B, H, NT, BT, S)
    if reverse:
        out = torch.flip(torch.cumsum(torch.flip(chunked, [-2]), dim=-2), [-2])
    else:
        out = torch.cumsum(chunked, dim=-2)
    out = out.view(B, H, T, S)
    if not head_first:
        out = out.transpose(1, 2).contiguous()  # -> (B, T, H, S)
    return out.to(g.dtype)


def _chunk_local_cumsum_vector(
    g: torch.Tensor,
    chunk_size: int,
    reverse: bool = False,
    head_first: bool = False,
    cu_seqlens: torch.Tensor | None = None,
) -> torch.Tensor:
    """Per-chunk local cumulative sum along the sequence axis (FLA).

    Dispatches to the varlen path when ``cu_seqlens`` is provided (matching
    the kernel's ``IS_VARLEN`` heuristic) and the fixed-length path
    otherwise. See the two helpers for the exact per-branch semantics.

    Args:
        g: rank-4 tensor. Varlen path requires the packed layout
            ``[1, total_T, H, S]`` with ``head_first=False``. Fixed-length
            path: ``[B, H, T, S]`` (``head_first=True``) or ``[B, T, H, S]``.
        chunk_size: BT block size; power of 2, >= 16.
        reverse: suffix cumsum within each chunk.
        head_first: input layout flag (forwarded from wrapper).
        cu_seqlens: optional 1-D int segment indptr -> varlen path.
    """
    if cu_seqlens is not None:
        return _chunk_local_cumsum_vector_varlen(
            g, chunk_size, cu_seqlens, reverse
        )
    return _chunk_local_cumsum_vector_fixed(g, chunk_size, reverse, head_first)


