from __future__ import annotations

import torch
import torch.nn.functional as F


def _alibi_attention(
    q: torch.Tensor, k: torch.Tensor, v: torch.Tensor,
    alibi_slopes: torch.Tensor, scale: float,
) -> torch.Tensor:
    """Causal SDPA with ALiBi positional bias. q/k/v: [H, L, D]
    (single sequence). bias_{ij} = -slope_h · (i - j)."""
    qf, kf, vf = q.to(torch.float32), k.to(torch.float32), v.to(torch.float32)
    H, L, D = qf.shape
    i = torch.arange(L, device=q.device)
    rel = (i[:, None] - i[None, :]).to(torch.float32)
    out = qf.new_zeros(qf.shape)
    for h in range(H):
        sc = (qf[h] @ kf[h].T) * scale
        sc = sc - float(alibi_slopes[h].item()) * rel
        sc = sc.masked_fill(i[None, :] > i[:, None], float("-inf"))
        out[h] = torch.softmax(sc, dim=-1) @ vf[h]
    return out.to(q.dtype)


