import torch
import torch.nn.functional as F


def _fused_moe_gemm(
    a: torch.Tensor, b: torch.Tensor, topk_weights: torch.Tensor,
    sorted_token_ids: torch.Tensor, expert_ids: torch.Tensor,
    block_size: int, apply_weight: bool = True,
) -> torch.Tensor:
    """Grouped MoE expert GEMM. For each padded block of sorted tokens,
    multiply by that block's expert weight; optionally scale by the
    token's routing weight. a: [n_tokens, K]; b: [n_experts, N, K];
    out: [n_padded, N]. Padding rows (token id == n_tokens) stay zero.
    """
    n_tok, K = a.shape
    N = b.shape[1]
    st = sorted_token_ids.to(torch.long)
    out = a.new_zeros((st.shape[0], N), dtype=torch.float32)
    af = a.to(torch.float32); bf = b.to(torch.float32)
    nblk = st.shape[0] // block_size
    for blk in range(nblk):
        e = int(expert_ids[blk].item())
        sl = slice(blk * block_size, (blk + 1) * block_size)
        toks = st[sl]
        valid = toks < n_tok
        rows = toks.clamp_max(n_tok - 1)
        y = af[rows] @ bf[e].T                       # [bs, N]
        if apply_weight:
            y = y * topk_weights.reshape(-1).to(torch.float32)[
                rows].unsqueeze(-1)
        out[sl] = y * valid.unsqueeze(-1)
    return out.to(a.dtype)


