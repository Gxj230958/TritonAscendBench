"""Oracle reference for L3_05_gate_up_lora_b_kernel.

Tier: formula_exact_manual
Tolerance class: vector_reduce
Category: gemm

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).

Upstream contract (sglang ``gate_up_lora_b_fwd`` / ``_gate_up_lora_b_kernel``):
the kernel packs two segmented GEMMs (gate and up LoRA-B expand) into one
launch. For each batch segment ``b`` it accumulates, for gate/up half
``g in {0, 1}``::

    w    = weight_indices[b]
    rank = lora_ranks[w]
    K    = min(r, rank)            # r = gate_up_lora_b.shape[-1]
    sc   = scalings[w]
    rows = seg rows for segment b  (permutation[seg] if sorted, else contiguous)
    output[rows, g*output_dim:(g+1)*output_dim] +=
        sc * ( x[rows, g*K : g*K + K] @ gate_up_lora_b[w, g*output_dim:(g+1)*output_dim, :K]^T )

Two upstream subtleties reproduced exactly:
  * the up half reads x starting at column ``g*K`` (= ``g*min(r, rank)``),
    NOT ``g*r`` -- when ``rank < r`` the up slice is offset by the clamped
    rank, matching the kernel's ``(gate_up_id * K) * x_stride_1`` pointer.
  * a ``rank == 0`` (or ``seg_len == 0``) segment is a no-op.

The result accumulates onto ``base_output`` when provided, else onto zeros,
mirroring the host that passes ``base_output`` straight through to the
read-modify-write ``+=`` in the kernel.
"""
from __future__ import annotations

import torch


def _to_tf32(x: torch.Tensor) -> torch.Tensor:
    """Round fp32 to TF32 (drop low 13 mantissa bits), matching the kernel's
    unpinned tl.dot on TF32 cores."""
    return (x.contiguous().view(torch.int32) & ~((1 << 13) - 1)).view(torch.float32)


def _segmented_gate_up_lora_b(
    x: torch.Tensor,
    weights: torch.Tensor,
    seg_indptr: torch.Tensor,
    weight_indices: torch.Tensor,
    lora_ranks: torch.Tensor,
    scalings: torch.Tensor,
    output_dim: int,
    permutation: torch.Tensor | None,
    base_output: torch.Tensor | None,
) -> torch.Tensor:
    """Gate/up segmented LoRA-B expand; see module docstring for the math.

    x: ``[S, 2*r]``; weights (gate_up_lora_b): ``[num_lora, 2*output_dim, r]``;
    output: ``[S, 2*output_dim]``. ``r`` is the max LoRA rank
    (``weights.shape[-1]``); only the first ``min(r, lora_ranks[w])`` rank
    columns of each x/weight half contribute.
    """
    n_tokens = x.shape[0]
    r = weights.shape[-1]
    out_cols = 2 * output_dim
    out = (
        base_output.to(torch.float32).clone()
        if base_output is not None
        else x.new_zeros((n_tokens, out_cols), dtype=torch.float32)
    )
    xf = x.to(torch.float32)
    wf = weights.to(torch.float32)
    seg = seg_indptr.to(torch.long).tolist()
    perm = None if permutation is None else permutation.to(torch.long)

    num_segments = len(seg) - 1
    for b in range(num_segments):
        s, e = seg[b], seg[b + 1]
        if e <= s:
            continue
        if perm is not None:
            rows = perm[s:e]
        else:
            rows = torch.arange(s, e, device=x.device)
        w = int(weight_indices[b].item())
        rank = int(lora_ranks[w].item())
        if rank <= 0:
            continue
        K = min(r, rank)
        sc = float(scalings[w].item())
        for g in range(2):
            x_half = xf[rows, g * K: g * K + K]                       # [seg_len, K]
            w_half = wf[w, g * output_dim:(g + 1) * output_dim, :K]   # [output_dim, K]
            contrib = sc * (_to_tf32(x_half) @ _to_tf32(w_half.T))                        # [seg_len, output_dim]
            out[rows, g * output_dim:(g + 1) * output_dim] += contrib
    return out.to(x.dtype)


def run(inputs: dict) -> dict:
    return {
        "output": _segmented_gate_up_lora_b(
            inputs["x"],
            inputs["gate_up_lora_b"],
            inputs["seg_indptr"],
            inputs["weight_indices"],
            inputs["lora_ranks"],
            inputs["scalings"],
            int(inputs["output_dim"]),
            inputs.get("permutation"),
            inputs.get("base_output"),
        )
    }
