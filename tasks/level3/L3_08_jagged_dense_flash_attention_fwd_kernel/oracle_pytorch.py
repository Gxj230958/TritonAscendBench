from __future__ import annotations

import torch
import torch.nn.functional as F


def _jagged_dense_flash_attention(
    Q: torch.Tensor, K: torch.Tensor, V: torch.Tensor,
    jagged_offsets: torch.Tensor, attn_bias: torch.Tensor | None,
    scale: float,
) -> torch.Tensor:
    """FBGEMM jagged (variable-length) dense flash attention.

    Q/K/V packed [total, H, D] with per-sequence spans from
    jagged_offsets. Full (non-causal) softmax attention per sequence,
    optional additive bias. Naive reference.
    """
    off = jagged_offsets.to(torch.long).tolist()
    H, D = Q.shape[1], Q.shape[2]
    out = Q.new_zeros(Q.shape, dtype=torch.float32)
    qf, kf, vf = Q.to(torch.float32), K.to(torch.float32), V.to(torch.float32)
    for i in range(len(off) - 1):
        s, e = off[i], off[i + 1]
        if e <= s:
            continue
        for h in range(H):
            sc = (qf[s:e, h] @ kf[s:e, h].T) * scale
            if attn_bias is not None:
                sc = sc + attn_bias[i, :e - s, :e - s].to(torch.float32)
            out[s:e, h] = torch.softmax(sc, dim=-1) @ vf[s:e, h]
    return out.to(Q.dtype)


