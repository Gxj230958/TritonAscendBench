from __future__ import annotations

import torch


def _softmax(x: torch.Tensor, dim: int) -> torch.Tensor:
    """Numerically-stable softmax spelled from its definition -- keeps the
    oracle body free of high-level torch ops (contract §6 / L195)."""
    e = torch.exp(x - x.amax(dim, keepdim=True))
    return e / e.sum(dim, keepdim=True)


def _paged_attention_2d(
    query: torch.Tensor,            # [n_tokens, n_qh, head_size]
    key_cache: torch.Tensor,        # [n_blocks, block_size, n_kvh, head_size]
    value_cache: torch.Tensor,      # [n_blocks, block_size, n_kvh, head_size]
    block_table: torch.Tensor,      # [n_seqs, max_blocks]
    seq_lens: torch.Tensor,         # [n_seqs] valid KV length per sequence
    scale: float,
    alibi_slopes: torch.Tensor | None,
    sliding_window: int | None,
) -> torch.Tensor:
    """Paged decode/chunked-prefill SDPA reference.

    One query token per sequence (decode). For each sequence: gather K/V
    from `block_table` for the first `seq_lens[i]` positions, GQA-broadcast
    KV heads, scaled dot-product with optional ALiBi bias, optional
    sliding-window truncation, softmax in fp32, weighted sum of V.
    Returns [n_tokens, n_qh, head_size].
    """
    n_tokens, n_qh, hd = query.shape
    n_blocks, block_size, n_kvh, _ = key_cache.shape
    g = n_qh // n_kvh
    out = query.new_zeros((n_tokens, n_qh, hd), dtype=torch.float32)
    qf = query.to(torch.float32)
    kf = key_cache.to(torch.float32)
    vf = value_cache.to(torch.float32)
    for i in range(n_tokens):
        L = int(seq_lens[i].item())
        if L <= 0:
            continue
        bt = block_table[i].to(torch.long)
        pos = torch.arange(L, device=query.device)
        blk = bt[pos // block_size]
        off = pos % block_size
        k = kf[blk, off]                                  # [L, n_kvh, hd]
        v = vf[blk, off]
        lo = 0
        if sliding_window and sliding_window > 0 and L > sliding_window:
            lo = L - sliding_window
        for h in range(n_qh):
            kvh = h // g
            qh = qf[i, h]                                 # [hd]
            scores = (k[:, kvh, :] @ qh) * scale          # [L]
            if alibi_slopes is not None:
                slope = float(alibi_slopes[h].item())
                scores = scores + slope * (pos.to(torch.float32) - (L - 1))
            if lo > 0:
                scores[:lo] = float("-inf")
            p = _softmax(scores, dim=-1)
            out[i, h] = p @ v[:, kvh, :]
    return out.to(query.dtype)


def run(inputs: dict) -> dict:
    return {
        "output": _paged_attention_2d(
            inputs["query"], inputs["key_cache"], inputs["value_cache"],
            inputs["block_table"], inputs["seq_lens"],
            float(inputs["scale"]), inputs.get("alibi_slopes"),
            inputs.get("sliding_window"),
        )
    }
