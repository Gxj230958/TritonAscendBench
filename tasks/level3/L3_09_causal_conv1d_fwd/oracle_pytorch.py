from __future__ import annotations

import torch
import torch.nn.functional as F


def _causal_conv1d_fwd(
    x: torch.Tensor, weight: torch.Tensor, bias: torch.Tensor | None,
    activation: str | None,
) -> torch.Tensor:
    """Depthwise causal 1-D conv (Mamba prefill), single sequence.

    x: [dim, seqlen]; weight: [dim, KERNEL_WIDTH]; bias: [dim]. Left-pad
    by KERNEL_WIDTH-1 zeros so
        output[d, t] = sum_{j} x[d, t - (KW-1) + j] * w[d, j] (+ bias[d]),
    with optional SiLU. Returns [dim, seqlen].

    Matches the frozen `_causal_conv1d_fwd_kernel` simple path (one
    sequence, no prior initial state): per channel the kernel accumulates
    a length-KW causal window dot product, adds the per-channel bias, and
    applies SiLU when requested.
    """
    dim, seqlen = x.shape
    kw = weight.shape[-1]
    xf = x.to(torch.float32)                                # [dim, L]
    wf = weight.to(torch.float32)                           # [dim, kw]
    xp = F.pad(xf, (kw - 1, 0))                             # [dim, L+kw-1]
    win = xp.unfold(-1, kw, 1)                              # [dim, L, kw]
    # Kernel accumulates `acc += matrix_x * matrix_w` with bf16 operands, so
    # each tap product is rounded to the input dtype before the fp32 add.
    prod = (win * wf.unsqueeze(1)).to(x.dtype).to(torch.float32)
    y = prod.sum(dim=-1)                                    # [dim, L]
    if bias is not None:
        y = y + bias.to(torch.float32).unsqueeze(-1)        # [dim, 1] broadcast
    if activation in ("silu", "swish"):
        y = F.silu(y)
    return y.to(x.dtype)


def run(inputs: dict) -> dict:
    return {
        "output": _causal_conv1d_fwd(
            inputs["x"], inputs["weight"], inputs.get("bias"),
            inputs.get("activation"),
        )
    }
