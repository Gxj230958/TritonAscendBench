"""Oracle reference for L3_09_fused_moe_kernel.

Tier: upstream_oracle_required
Tolerance class: atomic_scatter
Category: moe

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).
ORACLE-SCOPE (tier=upstream_oracle_required): covers grouped GEMM + topk
weight scatter into the token-id output domain; NOT covered: HAS_BIAS,
quantization (fp8/int8/int4), top_k > 1.

"""
from __future__ import annotations

import torch


def _to_tf32(x: torch.Tensor) -> torch.Tensor:
    """Round fp32 to TF32 (drop low 13 mantissa bits), matching the kernel's
    unpinned tl.dot on TF32 cores."""
    return (x.contiguous().view(torch.int32) & ~((1 << 13) - 1)).view(torch.float32)


def _fused_moe_gemm(
    a: torch.Tensor, b: torch.Tensor, topk_weights: torch.Tensor,
    sorted_token_ids: torch.Tensor, expert_ids: torch.Tensor,
    block_size: int, apply_weight: bool = True,
) -> torch.Tensor:
    """Grouped MoE expert GEMM with token-id scatter (the fused_moe_kernel
    output domain).

    For each padded block ``blk`` of ``block_size`` sorted slots, the block's
    expert ``e = expert_ids[blk]`` matmuls the gathered token rows by that
    expert's weight and (optionally) scales by the token's routing weight; the
    result row for slot ``s`` is scattered to ``out[sorted_token_ids[s]]`` --
    exactly what the kernel does via ``C[offs_token]`` (kernel.py:567). Slots
    holding the padding sentinel (``token id >= n_tokens``) are masked out and
    write nothing, so their rows -- and rows of tokens no slot routes -- stay
    zero.

    a: [n_tokens, K]; b: [n_experts, N, K]; out: [n_tokens, N]
    (top_k == 1, so the kernel's ``offs_token // top_k`` == ``offs_token`` and
    the output is indexed directly by token id).

    The fixture's ``sorted_token_ids`` are an injective moe_align_block_size
    buffer (``dist: moe_sorted_ids:B`` -- each token id appears at most once),
    so every scatter target is distinct and the result is order-independent.
    """
    n_tok, K = a.shape
    N = b.shape[1]
    st = sorted_token_ids.to(torch.long).reshape(-1)
    out = a.new_zeros((n_tok, N), dtype=torch.float32)
    af = a.to(torch.float32)
    bf = b.to(torch.float32)
    wf = topk_weights.reshape(-1).to(torch.float32)
    nblk = st.shape[0] // block_size
    for blk in range(nblk):
        e = int(expert_ids[blk].item())
        sl = slice(blk * block_size, (blk + 1) * block_size)
        toks = st[sl]
        valid = toks < n_tok                       # padding sentinel -> False
        if not bool(valid.any()):
            continue
        rows = toks[valid]                         # distinct token ids
        y = _to_tf32(af[rows]) @ _to_tf32(bf[e].T)                     # [n_valid, N]
        if apply_weight:
            y = y * wf[rows].unsqueeze(-1)
        out[rows] = y                              # scatter to token-id rows
    return out.to(a.dtype)


def run(inputs: dict) -> dict:
    return {"output": _fused_moe_gemm(
        inputs["a"], inputs["b"], inputs["topk_weights"],
        inputs["sorted_token_ids"], inputs["expert_ids"],
        int(inputs["block_size"]),
        bool(inputs.get("apply_weight", True)))}
