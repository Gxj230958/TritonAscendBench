from __future__ import annotations

import torch
import torch.nn.functional as F


def _compute_seg_indptr(topk_ids: torch.Tensor, num_experts: int) -> torch.Tensor:
    """Per-expert segment offsets: indptr[e+1]=indptr[e]+count(topk_ids==e)."""
    counts = torch.bincount(
        topk_ids.reshape(-1).to(torch.long), minlength=num_experts)
    indptr = torch.zeros(num_experts + 1, dtype=torch.int32,
                         device=topk_ids.device)
    indptr[1:] = torch.cumsum(counts, 0).to(torch.int32)
    return indptr


