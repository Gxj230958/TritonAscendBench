from __future__ import annotations

import torch
import torch.nn.functional as F


def _apply_min_p(
    logits: torch.Tensor, expanded_idx_mapping: torch.Tensor,
    min_p: torch.Tensor,
) -> torch.Tensor:
    """min-p filter: drop tokens whose prob < min_p * max_prob (per row).

    logits: [n_tokens, vocab]; expanded_idx_mapping: [n_tokens] → request
    index into min_p [n_reqs]. Returns a new logits tensor with filtered
    positions set to -inf (upstream mutates in place; the runner compares
    the resulting tensor either way).
    """
    out = logits.to(torch.float32).clone()
    probs = torch.softmax(out, dim=-1)
    max_prob = probs.max(dim=-1, keepdim=True).values
    mp = min_p.to(torch.float32)[expanded_idx_mapping.to(torch.long)].unsqueeze(-1)
    threshold = mp * max_prob
    mask = probs < threshold
    out = out.masked_fill(mask, float("-inf"))
    return out.to(logits.dtype)


def run(inputs: dict) -> dict:
    return {
        "logits": _apply_min_p(
            inputs["logits"], inputs["expanded_idx_mapping"], inputs["min_p"]
        ),
        "expanded_idx_mapping": inputs["expanded_idx_mapping"],
        "min_p": inputs["min_p"],
    }
