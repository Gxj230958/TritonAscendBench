"""Oracle reference for L1_38_silu_mul_fp8_quant_deep_gemm.

Tier: formula_exact_manual
Tolerance class: fp8_software_emulated
Category: moe

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).

Faithful to the vLLM `_silu_mul_fp8_quant_deep_gemm` @triton.jit kernel
(batched_deep_gemm_moe.py): per (expert e, hidden group g) and each valid
token t < tokens_per_expert[e],

    gate    = silu(y[e, t, g_cols])           # f32
    up      = y[e, t, H + g_cols]
    z       = gate * up
    y_s     = max(max(|z|), eps) * (1 / fp8_max)   # eps floors AMAX
    y_q     = clamp(z / y_s, -fp8_max, fp8_max) -> fp8_e4m3fn

with GROUP_SIZE == 128, eps == 1e-10, and the FLOAT32 scale format
(ceil_ue8m0 == False, the Triton-fallback path the oracle covers).
Tokens t >= tokens_per_expert[e] are never written by the kernel; the
launcher zero-inits both outputs, so the invalid rows are deterministic
0 in BOTH y_q and y_s and are masked to 0 here to compare equal.

ORACLE-SCOPE: covers DeepGemmQuantScaleFMT.FLOAT32 (ceil_ue8m0 == False),
the format the Triton fallback supports (it asserts y_s.dtype == float32).
NOT covered: the FLOAT32_CEIL_UE8M0 / UE8M0 scale formats (ceil_ue8m0 ==
True, y_s = exp2(ceil(log2(y_s)))) -- a host-wrapper format choice, not a
kernel input the fixture varies.
"""
from __future__ import annotations

import torch


def _silu(t: torch.Tensor) -> torch.Tensor:
    """SiLU spelled from its definition x * sigmoid(x) = x / (1 + exp(-x)),
    matching the kernel's `gate * (1.0 / (1.0 + tl.exp(-gate)))`."""
    return t / (1.0 + torch.exp(-t))


def _silu_mul_fp8_quant(
    y: torch.Tensor, tokens_per_expert: torch.Tensor, group_size: int,
    fp8_max: float = 448.0, eps: float = 1e-10,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Masked SiLU*mul -> per-group FP8 quant (DeepGEMM MoE path).

    y: [E, T, 2H]. Only first tokens_per_expert[e] rows are valid. The
    AMAX is floored at eps=1e-10 BEFORE dividing by fp8_max (the kernel's
    `y_s = tl.maximum(tl.max(tl.abs(y)), eps) * (1.0 / fp8_max)`), NOT a
    post-divide clamp on the scale.
    """
    E, T, two_h = y.shape
    h = two_h // 2
    gate, up = y[..., :h], y[..., h:]
    z = (_silu(gate.to(torch.float32)) * up.to(torch.float32))     # [E,T,H]
    tok = torch.arange(T, device=y.device).view(1, T)
    valid = tok < tokens_per_expert.to(torch.long).view(E, 1)
    z = z * valid.unsqueeze(-1)
    g = group_size
    zv = z.reshape(E, T, h // g, g)
    amax = zv.abs().amax(dim=-1, keepdim=True)
    amax = torch.maximum(
        amax, torch.tensor(eps, dtype=amax.dtype, device=amax.device)
    )
    s = amax * (1.0 / float(fp8_max))
    q = (zv / s).clamp(-float(fp8_max), float(fp8_max)).reshape(E, T, h)
    q = q.to(torch.float8_e4m3fn)
    s = s.squeeze(-1).reshape(E, T, h // g)
    # Tokens t >= tokens_per_expert[e] are never written by the kernel; the
    # launcher zero-inits both outputs. q is already 0 there (z was masked
    # above); mask the scale rows to 0 as well so the invalid rows compare
    # equal under the harness full-tensor compare.
    s = s * valid.unsqueeze(-1)
    return q, s


def run(inputs: dict) -> dict:
    q, s = _silu_mul_fp8_quant(
        inputs["y"], inputs["tokens_per_expert"],
        int(inputs["group_size"]), float(inputs.get("fp8_max", 448.0)))
    return {"output": q, "scale": s}
