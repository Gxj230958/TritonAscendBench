from __future__ import annotations

import torch
import torch.nn.functional as F


def _silu_mul_fp8_quant(
    y: torch.Tensor, tokens_per_expert: torch.Tensor, group_size: int,
    fp8_max: float = 448.0,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Masked SiLU·mul → per-group FP8 quant (DeepGEMM MoE path).

    y: [E, T, 2H]. Only first tokens_per_expert[e] rows valid. Same
    structure as L2_37 but FP8 (e4m3) output + group scale.
    """
    E, T, two_h = y.shape
    h = two_h // 2
    gate, up = y[..., :h], y[..., h:]
    z = (F.silu(gate.to(torch.float32)) * up.to(torch.float32))
    tok = torch.arange(T, device=y.device).view(1, T)
    valid = tok < tokens_per_expert.to(torch.long).view(E, 1)
    z = z * valid.unsqueeze(-1)
    g = group_size
    zv = z.reshape(E, T, h // g, g)
    s = (zv.abs().amax(-1, keepdim=True) / float(fp8_max)).clamp_min(1e-12)
    q = (zv / s).clamp(-float(fp8_max), float(fp8_max)).reshape(E, T, h)
    return q.to(torch.float8_e4m3fn), s.squeeze(-1).reshape(E, T, h // g)


def run(inputs: dict) -> dict:
    q, s = _silu_mul_fp8_quant(
        inputs["y"], inputs["tokens_per_expert"],
        int(inputs["group_size"]), float(inputs.get("fp8_max", 448.0)))
    return {"output": q, "scale": s}
