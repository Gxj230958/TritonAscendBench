from __future__ import annotations

import torch
import torch.nn.functional as F


def _rotate_half(x: torch.Tensor) -> torch.Tensor:
    h = x.shape[-1] // 2
    return torch.cat([-x[..., h:], x[..., :h]], dim=-1)


def _triton_mrope(
    q: torch.Tensor, k: torch.Tensor, cos: torch.Tensor, sin: torch.Tensor,
    mrope_section: list[int], head_size: int, rotary_dim: int,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Qwen2-VL multimodal RoPE (non-interleaved / chunked layout).

    q: [n_tokens, n_qh*head_size]; k: [n_tokens, n_kh*head_size].
    cos/sin: [3, n_tokens, rotary_dim//2] for the T/H/W position
    channels. mrope_section = [t,h,w] (sums to rotary_dim//2): the first
    t frequencies take their angle from channel 0 (T), the next h from
    channel 1 (H), the last w from channel 2 (W). Standard rotate_half
    RoPE is applied to the first `rotary_dim` dims of each head; the
    pass-through tail (head_size - rotary_dim) is untouched.
    """
    n = q.shape[0]
    half = rotary_dim // 2
    t, h, w = mrope_section
    sel = torch.cat([
        cos.new_zeros(t, dtype=torch.long),
        cos.new_ones(h, dtype=torch.long),
        cos.new_full((w,), 2, dtype=torch.long),
    ])                                                   # [half] channel id
    tok = torch.arange(n, device=q.device)
    cos_sel = cos[sel, tok[:, None], torch.arange(half, device=q.device)]
    sin_sel = sin[sel, tok[:, None], torch.arange(half, device=q.device)]
    cos_f = torch.cat([cos_sel, cos_sel], dim=-1)        # [n, rotary_dim]
    sin_f = torch.cat([sin_sel, sin_sel], dim=-1)

    def _apply(x: torch.Tensor, n_heads: int) -> torch.Tensor:
        xr = x.reshape(n, n_heads, head_size).to(torch.float32)
        rot = xr[..., :rotary_dim]
        c = cos_f.unsqueeze(1)
        s = sin_f.unsqueeze(1)
        rot = rot * c + _rotate_half(rot) * s
        out = xr.clone()
        out[..., :rotary_dim] = rot
        return out.reshape(n, n_heads * head_size).to(x.dtype)

    n_qh = q.shape[1] // head_size
    n_kh = k.shape[1] // head_size
    return _apply(q, n_qh), _apply(k, n_kh)


def run(inputs: dict) -> dict:
    rotary_dim = int(inputs.get("rotary_dim", inputs["cos"].shape[-1] * 2))
    head_size = int(inputs.get("head_size", rotary_dim))
    q_out, k_out = _triton_mrope(
        inputs["q"], inputs["k"], inputs["cos"], inputs["sin"],
        list(inputs["mrope_section"]), head_size, rotary_dim,
    )
    return {"q": q_out, "k": k_out}
