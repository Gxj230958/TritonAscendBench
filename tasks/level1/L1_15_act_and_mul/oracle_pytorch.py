"""Oracle reference for L1_15_act_and_mul_kernel.

Tier: upstream_oracle_required
Tolerance class: elementwise
Category: elementwise

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).
ORACLE-SCOPE (tier=upstream_oracle_required): covers silu/gelu/relu act·mul
over the MoE-routed unsorted path (per-token expert ids, -1 = dropped token);
NOT covered: HAS_SWIGLU_LIMIT clamp variant, the sorted/TMA routing layout.

"""
from __future__ import annotations

import math

import torch


# Reference for SGLang's `act_and_mul_kernel` (MoE down-proj gate), unsorted
# routing path. The frozen @triton.jit launches one program per output row
# `pid` and does, for the unsorted layout (expert_step == 1, so the lookup is
# `expert_ids[pid]`):
#     expert_id = topk_ids[pid]
#     if expert_id == -1: return            # dropped token -> row left untouched
#     gate, up = gateup_output[pid, :half], gateup_output[pid, half:]
#     down_input[pid] = act(gate).to(in_dtype) * up
# So `topk_ids == -1` is the load-bearing routing mask: those rows are never
# written. The launcher zero-inits the output, so a dropped row stays 0; the
# oracle masks the same rows to 0 to match bit-exact (and to discriminate any
# kernel that ignores `topk_ids` and writes every row).
#
# Activations are spelled out from their mathematical definitions (no
# high-level torch ops) so this oracle body stays a primitive expansion
# per task_api_contract.md §6 / L195. Composite activations decompose to
# basic-math primitives (exp/abs); tanh itself is a high-level op:
#   silu(x) = x * sigmoid(x) = x / (1 + exp(-x))
#   gelu_tanh(x) = 0.5*x*(1 + tanh(sqrt(2/pi)*(x + 0.044715*x^3)))
#   tanh(u)  = sign(u) * (1 - e) / (1 + e),  e = exp(-2*|u|)  [overflow-safe]
#   relu(x) = max(x, 0)
def _tanh(u: torch.Tensor) -> torch.Tensor:
    # Overflow-safe tanh via exp on -2*|u| so large |u| never overflows.
    e = torch.exp(-2.0 * torch.abs(u))
    return torch.sign(u) * (1.0 - e) / (1.0 + e)


def _silu(t: torch.Tensor) -> torch.Tensor:
    return t / (1.0 + torch.exp(-t))


def _gelu_tanh(t: torch.Tensor) -> torch.Tensor:
    c = math.sqrt(2.0 / math.pi)
    return 0.5 * t * (1.0 + _tanh(c * (t + 0.044715 * t * t * t)))


def _relu(t: torch.Tensor) -> torch.Tensor:
    return torch.clamp_min(t, 0.0)


_ACT_FNS = {
    "silu": _silu,
    "gelu": _gelu_tanh,
    "relu": _relu,
}


def _act_and_mul_routed(
    gateup_output: torch.Tensor, topk_ids: torch.Tensor, act: str = "silu"
) -> torch.Tensor:
    half = gateup_output.shape[-1] // 2
    gate, up = gateup_output[..., :half], gateup_output[..., half:]
    fn = _ACT_FNS[act]
    # SGLang upstream casts the activated gate back to the input dtype BEFORE
    # the `* up` multiply (kernel: gate_output_activated.to(InDtype)); mirror
    # that so the oracle matches the kernel's intermediate-precision rounding.
    activated = fn(gate.to(torch.float32)).to(gateup_output.dtype)
    y = activated * up

    # Routing mask: rows whose expert id is -1 (dropped token) are never
    # written by the kernel; keep them 0 to match the launcher's zero-init.
    valid = (topk_ids.view(-1) != -1).view(*([gateup_output.shape[0]] + [1] * (y.ndim - 1)))
    return torch.where(valid, y, torch.zeros_like(y))


def run(inputs: dict) -> dict:
    return {
        "output": _act_and_mul_routed(
            inputs["gateup_output"],
            inputs["topk_ids"],
            act=inputs.get("act", "silu"),
        )
    }
