"""Oracle reference for L1_13_layer_norm_fwd_kernel.

Tier: upstream_oracle_required
Tolerance class: vector_reduce
Category: normalization

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).
ORACLE-SCOPE (tier=upstream_oracle_required): covers LayerNorm with affine
(HAS_BIAS) AND the SiLU gating branch (HAS_Z) at the wrapper default
norm_before_gate=True (gate applied AFTER normalisation) with activation
"swish". The non-default IS_RMS_NORM, sigmoid-activation, and gate-before-norm
paths are separate kernel modes a single task config cannot also drive.

"""
from __future__ import annotations

import torch


def _layer_norm(
    x: torch.Tensor, weight: torch.Tensor, bias: torch.Tensor | None,
    z: torch.Tensor | None, eps: float,
) -> torch.Tensor:
    """Gated LayerNorm: mean/var normalise + affine, then SiLU gate.

    Mirrors ``layer_norm_fwd`` / ``layer_norm_fwd_kernel`` (non-RMS,
    norm_before_gate=True, activation="swish"): mean/var normalise along the
    last dim, scale + shift, then -- when a gating tensor ``z`` is present --
    multiply by the SiLU gate ``z * sigmoid(z)``. This is the gate-after-norm
    branch (``if HAS_Z and NORM_BEFORE_GATE: y *= z * sigmoid(z)``).
    """
    x_f = x.to(torch.float32)
    mean = x_f.mean(dim=-1, keepdim=True)
    var = x_f.var(dim=-1, keepdim=True, unbiased=False)
    inv = torch.rsqrt(var + float(eps))
    out = (x_f - mean) * inv
    out = out * weight.to(torch.float32)
    if bias is not None:
        out = out + bias.to(torch.float32)
    if z is not None:
        z_f = z.to(torch.float32)
        out = out * (z_f * torch.sigmoid(z_f))
    return out.to(x.dtype)


def run(inputs: dict) -> dict:
    return {
        "output": _layer_norm(
            inputs["x"], inputs["weight"],
            inputs.get("bias"), inputs.get("z"),
            float(inputs.get("eps", 1e-5)),
        )
    }
