from __future__ import annotations

import torch
import torch.nn.functional as F


def _dequantize_k_cache_paged(
    nope_q: torch.Tensor, nope_s: torch.Tensor, rope: torch.Tensor,
    page_table: torch.Tensor, group_size: int,
) -> torch.Tensor:
    """Paged variant of the MLA K-cache dequant. Gathers physical pages
    via page_table, then per-group dequant of the nope part and rope
    passthrough (same math as the non-paged dequant)."""
    pt = page_table.to(torch.long).reshape(-1)
    nq = nope_q[pt].to(torch.float32)
    ns = nope_s[pt].to(torch.float32)
    rp = rope[pt].to(torch.float32)
    *lead, dn = nq.shape
    gs = group_size
    deq = (nq.reshape(*lead, dn // gs, gs)
           * ns.reshape(*lead, dn // gs, 1)).reshape(*lead, dn)
    return torch.cat([deq, rp], dim=-1).to(rope.dtype)


