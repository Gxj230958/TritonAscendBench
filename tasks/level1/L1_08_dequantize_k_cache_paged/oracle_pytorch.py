"""Oracle reference for L1_08_dequantize_k_cache_paged_kernel.

Tier: formula_exact_manual
Tolerance class: elementwise_exact_or_inf_safe
Category: attention

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).

Upstream contract (SGLang ``dequantize_k_cache_paged``,
``sglang/srt/layers/attention/nsa/dequant_k_cache.py``): the input is a
single PACKED fp8 K-cache tensor ``quant_k_cache`` (dtype
``float8_e4m3fn``) reshaped to ``[C, 656]`` (C physical cache rows) plus a
flattened paged index ``page_table_1_flattened[B]`` (int64). For each of
the B output tokens the kernel gathers physical row
``token_id_paged = page_table_1_flattened[token_id]`` and dequantises it.

Each gathered 656 byte-lane row is unpacked by slice + byte reinterpret
exactly as the frozen wrapper does (identical to the non-paged sibling
L1_07):

    nope_q = row[:, :512]                     # fp8 [B, 512]
    nope_s = row[:, 512:528].view(float32)    # [B, 4] scales
    rope   = row[:, 528:656].view(bfloat16)   # [B, 64] passthrough

The nope half is per-128-group dequantised
(``out[:, j] = nope_q[:, j].float() * nope_s[:, j // 128]``) and cast to
bf16; the rope half is a straight passthrough. The kernel writes
``output[B, 1, 576]`` bf16 == concat(dequant_nope[B, 512], rope[B, 64])
with a singleton head dim.
"""
from __future__ import annotations

import torch

# Frozen upstream constants (kernel.py ``dequantize_k_cache_paged``).
_DIM_QUANT = 656
_DIM_NOPE = 512
_DIM_ROPE = 64
_GROUP_SIZE = 128
_NUM_TILES = _DIM_NOPE // _GROUP_SIZE  # 4


def _dequantize_k_cache_paged(
    quant_k_cache: torch.Tensor,
    page_table_1_flattened: torch.Tensor,
) -> torch.Tensor:
    """Independent PyTorch reproduction of the frozen triton kernel.

    Reproduces the exact paged gather + unpack + per-group dequant + rope
    passthrough of SGLang ``dequantize_k_cache_paged``. Never calls the
    kernel.

    quant_k_cache: packed fp8 (``float8_e4m3fn``); reshaped to ``[C, 656]``.
    page_table_1_flattened: ``[B]`` int64 physical-row indices in ``[0, C)``.
    Returns ``[B, 1, 576]`` bf16.
    """
    assert quant_k_cache.dtype == torch.float8_e4m3fn, (
        f"quant_k_cache must be float8_e4m3fn, got {quant_k_cache.dtype}"
    )
    # The kernel reshapes to [-1, dim_quant] before gathering rows.
    quant_k_cache = quant_k_cache.reshape(-1, _DIM_QUANT)
    dim_quant = quant_k_cache.shape[-1]
    assert dim_quant == _DIM_QUANT, f"dim_quant {dim_quant} != {_DIM_QUANT}"

    # Paged gather: select one physical row per output token. The kernel
    # loads token_id_paged = page_table_1_flattened[token_id] and addresses
    # the source tensors at that row; gathering the packed bytes first and
    # then unpacking is byte-identical (the slices are the same byte-lanes).
    pt = page_table_1_flattened.to(torch.long).reshape(-1)
    gathered = quant_k_cache[pt]  # [B, 656] fp8

    # Byte-reinterpret unpack -- identical to the frozen wrapper's slicing.
    input_nope_q = gathered[:, :_DIM_NOPE]
    input_nope_s = gathered[
        :, _DIM_NOPE : _DIM_NOPE + _NUM_TILES * 4
    ].view(torch.float32)
    input_rope = gathered[:, _DIM_NOPE + _NUM_TILES * 4 :].view(
        torch.bfloat16
    )

    num_tokens = gathered.shape[0]

    # Per-128-group dequant: out[:, j] = nope_q[:, j].float() * nope_s[:, j//128].
    qv = input_nope_q.to(torch.float32).reshape(
        num_tokens, _NUM_TILES, _GROUP_SIZE
    )
    sv = input_nope_s.to(torch.float32).reshape(num_tokens, _NUM_TILES, 1)
    # fp32 product then round-to-nearest-even cast to bf16 -- byte-identical to
    # the kernel's `(y_q * y_s).to(output.dtype.element_ty)` on a real device.
    # The CPU TRITON_INTERPRET=1 cast truncates instead of RNE (a tooling
    # artifact), so the anchor is GPU-re-confirmed; on the device the fp32
    # product and RNE bf16 cast are identical to the kernel's, so the output is
    # bit-exact -- hence the exact tolerance (garbage byte-reinterpreted scales
    # may produce inf/nan, which must match position-for-position).
    dequant_nope = (qv * sv).reshape(num_tokens, _DIM_NOPE).to(torch.bfloat16)

    # rope half is a straight bf16 passthrough.
    out = torch.cat([dequant_nope, input_rope.to(torch.bfloat16)], dim=-1)
    # Match the kernel's [num_tokens, 1, dim_nope + dim_rope] singleton head dim.
    return out.reshape(num_tokens, 1, _DIM_NOPE + _DIM_ROPE)


def run(inputs: dict) -> dict:
    return {"output": _dequantize_k_cache_paged(
        inputs["quant_k_cache"], inputs["page_table_1_flattened"])}
