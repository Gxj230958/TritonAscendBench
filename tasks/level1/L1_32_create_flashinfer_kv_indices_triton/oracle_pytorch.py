from __future__ import annotations

import torch
import torch.nn.functional as F


def _create_kv_indices(
    seq_lens: torch.Tensor, block_table: torch.Tensor, page_size: int,
) -> tuple[torch.Tensor, torch.Tensor]:
    """FlashInfer/FlashMLA paged KV index construction.

    indptr[0]=0, indptr[r+1]=indptr[r]+ceil(seq_lens[r]/page_size);
    indices = concatenation of the used page ids per request.
    """
    n = seq_lens.shape[0]
    counts = (seq_lens.to(torch.long) + page_size - 1) // page_size
    indptr = torch.zeros(n + 1, dtype=torch.int32, device=seq_lens.device)
    indptr[1:] = torch.cumsum(counts, 0).to(torch.int32)
    parts = [block_table[r, :int(counts[r].item())].to(torch.int32)
             for r in range(n)]
    indices = torch.cat(parts) if parts else block_table.new_zeros(0, dtype=torch.int32)
    return indptr, indices


def run(inputs: dict) -> dict:
    indptr, indices = _create_kv_indices(
        inputs["seq_lens"], inputs["block_table"], int(inputs["page_size"]))
    return {"kv_indptr": indptr, "kv_indices": indices}
