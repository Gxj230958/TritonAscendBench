from __future__ import annotations

import torch
import torch.nn.functional as F


def _chunk_cumsum_fwd(
    dt: torch.Tensor, A: torch.Tensor, dt_bias: torch.Tensor | None,
    dt_softplus: bool, dt_limit: tuple[float, float] | None,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Mamba2 chunk cumsum: dt' = softplus(dt + dt_bias) (clamped to
    dt_limit); dA_cumsum = cumsum(A · dt') along the sequence.
    dt: [..., L]; A: [...] (per-head). Returns (dt', dA_cumsum).
    """
    d = dt.to(torch.float32)
    if dt_bias is not None:
        d = d + dt_bias.to(torch.float32)
    if dt_softplus:
        d = F.softplus(d)
    if dt_limit is not None:
        d = d.clamp(float(dt_limit[0]), float(dt_limit[1]))
    dA = (A.to(torch.float32).unsqueeze(-1) * d).cumsum(dim=-1)
    return d.to(dt.dtype), dA.to(dt.dtype)


def run(inputs: dict) -> dict:
    dl = inputs.get("dt_limit")
    dtp, dA = _chunk_cumsum_fwd(
        inputs["dt"], inputs["A"], inputs.get("dt_bias"),
        bool(inputs.get("dt_softplus", True)),
        tuple(dl) if dl is not None else None)
    return {"dt_out": dtp, "dA_cumsum": dA}
