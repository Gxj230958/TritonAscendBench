from __future__ import annotations

import torch
import torch.nn.functional as F


def _dequantize_k_cache(
    nope_q: torch.Tensor, nope_s: torch.Tensor, rope: torch.Tensor,
    group_size: int,
) -> torch.Tensor:
    """DeepSeek-MLA K cache dequant: nope part is per-group quantized,
    rope part is stored unquantized. Returns concat(dequant_nope, rope)
    along the last dim.

    nope_q: [..., DIM_NOPE]; nope_s: [..., DIM_NOPE/group_size];
    rope: [..., DIM_ROPE]. dequant_nope[g] = nope_q[g] * nope_s[g//gs].
    """
    *lead, dn = nope_q.shape
    gs = group_size
    qv = nope_q.to(torch.float32).reshape(*lead, dn // gs, gs)
    sv = nope_s.to(torch.float32).reshape(*lead, dn // gs, 1)
    deq = (qv * sv).reshape(*lead, dn)
    return torch.cat([deq, rope.to(torch.float32)], dim=-1).to(rope.dtype)


