from __future__ import annotations

import torch
import torch.nn.functional as F


def _per_token_group_quant_int8(
    x: torch.Tensor, group_size: int, eps: float = 1e-10,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Symmetric per-(token,group) INT8 quant.

    x: [..., N] with N % group_size == 0. For each contiguous group of
    `group_size` elements: s = amax(|g|) / 127 (floored by eps);
    q = round(g / s).clamp(-128, 127). Returns (q int8, s fp32 [..., N/g]).
    """
    *lead, n = x.shape
    g = group_size
    xv = x.to(torch.float32).reshape(*lead, n // g, g)
    amax = xv.abs().amax(dim=-1, keepdim=True).clamp_min(eps)
    s = amax / 127.0
    q = torch.round(xv / s).clamp_(-128, 127).to(torch.int8)
    return q.reshape(*lead, n), s.squeeze(-1).reshape(*lead, n // g)


