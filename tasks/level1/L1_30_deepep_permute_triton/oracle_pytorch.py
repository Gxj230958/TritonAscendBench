def _deepep_permute(
    x: torch.Tensor, src2dst: torch.Tensor, topk: int,
) -> torch.Tensor:
    """DeepEP dispatch permute: replicate each token to its topk slots,
    placed at out[src2dst[i*topk + j]] = x[i]."""
    n = x.shape[0]
    out = x.new_zeros((n * topk, *x.shape[1:]))
