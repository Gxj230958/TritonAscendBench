from __future__ import annotations

import torch
import torch.nn.functional as F


# AWQ packs 8 int4 lanes per int32 in the de-interleaved order below
# (the public vLLM/AWQ "reverse" order). Unpacking must apply the same
# permutation to weights and zero-points before dequantising.
_AWQ_ORDER = [0, 4, 1, 5, 2, 6, 3, 7]


def _awq_unpack(packed: torch.Tensor) -> torch.Tensor:
    """[..., C] int32 → [..., C*8] int4 values (0..15) in logical order."""
    shifts = torch.tensor([o * 4 for o in _AWQ_ORDER],
                          device=packed.device, dtype=torch.int32)
    p = packed.to(torch.int32).unsqueeze(-1)
    vals = (p >> shifts) & 0xF                          # [..., C, 8]
    *lead, c, _ = vals.shape
    return vals.reshape(*lead, c * 8)


def _awq_dequantize(
    qweight: torch.Tensor, scales: torch.Tensor, zeros: torch.Tensor,
    group_size: int,
) -> torch.Tensor:
    """w = (unpack(qweight) - unpack(zeros)) * scales[group]."""
    w = _awq_unpack(qweight).to(torch.float32)              # [R, C*8]
    z = _awq_unpack(zeros).to(torch.float32)                # [R/g, C*8]
    r = w.shape[0]
    grp = torch.arange(r, device=w.device) // group_size
    return ((w - z[grp]) * scales.to(torch.float32)[grp]).to(scales.dtype)


def run(inputs: dict) -> dict:
    qweight, scales, zeros = inputs["qweight"], inputs["scales"], inputs["zeros"]
    # group_size: the kernel derives it from shapes, not a param it takes.
    group_size = qweight.shape[0] // scales.shape[0]
    return {"output": _awq_dequantize(qweight, scales, zeros, group_size)}
