from __future__ import annotations

import torch


def _layer_norm_1pass(
    x: torch.Tensor, weight: torch.Tensor, bias: torch.Tensor | None,
    eps: float,
) -> torch.Tensor:
    """Single-pass LayerNorm with affine, fp32 intermediate.

    Matches the upstream ``_layer_norm_fwd`` host wrapper of
    ``_layer_norm_fwd_1pass_kernel`` for the non-RMS, no-gate (Z=None)
    path: mean/var normalise along the last dim then scale + shift.
    The upstream kernel has no residual add; its optional second branch
    is the gating tensor ``z`` (z * sigmoid(z)), which this oracle scopes
    out (Z=None).
    """
    x_f = x.to(torch.float32)
    mean = x_f.mean(dim=-1, keepdim=True)
    var = x_f.var(dim=-1, keepdim=True, unbiased=False)
    inv = torch.rsqrt(var + float(eps))
    out = (x_f - mean) * inv * weight.to(torch.float32)
    if bias is not None:
        out = out + bias.to(torch.float32)
    return out.to(x.dtype)


def run(inputs: dict) -> dict:
    return {
        "output": _layer_norm_1pass(
            inputs["x"], inputs["weight"], inputs.get("bias"),
            float(inputs.get("eps", 1e-5)),
        )
    }
