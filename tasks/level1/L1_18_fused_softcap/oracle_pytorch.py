from __future__ import annotations

import torch
import torch.nn.functional as F


def _softcap(x: torch.Tensor, cap: float) -> torch.Tensor:
    """Logit softcap: cap * tanh(x / cap). Stabilises pre-softmax logits."""
    if cap <= 0:
        return x
    scale = float(cap)
    return (scale * torch.tanh(x.to(torch.float32) / scale)).to(x.dtype)


def run(inputs: dict) -> dict:
    return {"output": _softcap(inputs["x"], cap=float(inputs.get("cap", 30.0)))}
