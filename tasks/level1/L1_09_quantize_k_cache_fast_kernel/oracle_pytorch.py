from __future__ import annotations

import torch
import torch.nn.functional as F


def _quantize_k_cache(
    k_nope: torch.Tensor, k_rope: torch.Tensor, group_size: int,
    fp8_max: float = 448.0,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Inverse of dequant: per-group symmetric FP8 quant of the nope part,
    rope passed through. s = amax(|group|) / fp8_max; q = group / s cast
    to float8_e4m3fn. Returns (nope_q fp8, nope_s fp32, rope passthrough).
    """
    *lead, dn = k_nope.shape
    gs = group_size
    xv = k_nope.to(torch.float32).reshape(*lead, dn // gs, gs)
    s = (xv.abs().amax(dim=-1, keepdim=True) / float(fp8_max)).clamp_min(1e-12)
    q = (xv / s).clamp(-float(fp8_max), float(fp8_max))
    q_fp8 = q.reshape(*lead, dn).to(torch.float8_e4m3fn)
    return q_fp8, s.squeeze(-1).reshape(*lead, dn // gs), k_rope


