from __future__ import annotations

import torch
import torch.nn.functional as F


def _copy_page_indices(
    block_table: torch.Tensor, seq_lens: torch.Tensor, page_size: int,
) -> torch.Tensor:
    """Flatten per-request used page ids into a 1-D kv_indices vector
    (FlashInfer layout). For request r, emit ceil(seq_lens[r]/page_size)
    page ids from block_table[r]."""
    out = []
    for r in range(seq_lens.shape[0]):
        n = (int(seq_lens[r].item()) + page_size - 1) // page_size
        out.append(block_table[r, :n].to(torch.int32))
    return torch.cat(out) if out else block_table.new_zeros(0, dtype=torch.int32)


def run(inputs: dict) -> dict:
    return {"kv_indices": _copy_page_indices(
        inputs["block_table"], inputs["seq_lens"], int(inputs["page_size"]))}
