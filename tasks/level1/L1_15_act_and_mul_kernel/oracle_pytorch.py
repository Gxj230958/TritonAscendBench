from __future__ import annotations

import torch
import torch.nn.functional as F


# Reference for the generic act*mul fused op. The exact activation is
# tied to the kernel's autotune/template choice; default to SiLU which
# is the most common production path. Override via inputs["act"].
_ACT_FNS = {
    "silu": F.silu,
    "gelu": lambda t: F.gelu(t, approximate="tanh"),
    "relu": F.relu,
}


def _act_and_mul(x: torch.Tensor, act: str = "silu") -> torch.Tensor:
    half = x.shape[-1] // 2
    gate, up = x[..., :half], x[..., half:]
    fn = _ACT_FNS[act]
    return fn(gate.to(torch.float32)).to(x.dtype) * up


def run(inputs: dict) -> dict:
    return {"output": _act_and_mul(inputs["x"], act=inputs.get("act", "silu"))}
