from __future__ import annotations

import torch
import torch.nn.functional as F


def _deepep_run_moe_deep_preprocess(
    topk_ids: torch.Tensor, num_experts: int,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Mirror ``kernel.py::deepep_run_moe_deep_preprocess`` (line 176).

    Wrapper steps:
      1. ``reorder_topk_ids, reorder_ids = torch.sort(topk_ids.view(-1), stable=True)``
      2. ``seg_indptr`` via ``torch.searchsorted(reorder_topk_ids, [0..num_experts])``
      3. ``seg_indptr -= seg_indptr[0]`` (strip the -1 padding offset --
         ``seg_indptr[0]`` = count of entries strictly less than 0
         in the input, i.e. the ``num_minus_one`` padding count)
      4. ``src2dst[reorder_ids[i]] = i - num_minus_one`` via the
         ``deepep_compute_src2dst_triton_kernel`` -- a pure scatter,
         expressed here as fancy-index assignment.
      5. ``reorder_topk_ids = reorder_topk_ids[num_minus_one:]`` to
         drop the -1 padding prefix.

    Returns ``(reorder_topk_ids, src2dst, seg_indptr)`` in wrapper
    return order.
    """
    flat = topk_ids.view(-1).to(torch.int64)
    reorder_topk_ids_full, reorder_ids = torch.sort(flat, stable=True)

    # Step 2-3
    expert_ids = torch.arange(
        num_experts + 1,
        device=topk_ids.device,
        dtype=reorder_topk_ids_full.dtype,
    )
    seg_indptr_raw = torch.searchsorted(
        reorder_topk_ids_full, expert_ids
    ).to(torch.int64)
    num_minus_one = int(seg_indptr_raw[0].item())
    seg_indptr = seg_indptr_raw - seg_indptr_raw[0]

    # Step 4
    n = flat.numel()
    dst_id = torch.arange(n, device=topk_ids.device, dtype=torch.int64)
    src2dst = torch.empty(n, device=topk_ids.device, dtype=torch.int64)
    src2dst[reorder_ids] = dst_id - num_minus_one

    # Step 5
    reorder_topk_ids = reorder_topk_ids_full[num_minus_one:]

    return reorder_topk_ids, src2dst, seg_indptr


