    reorder_topk_ids, src2dst, seg_indptr = (
        _deepep_run_moe_deep_preprocess(
            inputs["topk_ids"], int(inputs["num_experts"])
        )
    )
    # IMPORTANT (V9 R10 multi-output convention): the dict insertion
    # order MUST match the wrapper's positional tuple return order.
    # R10.a stamps this order into safetensors metadata so the R10.b
    # runner can map ``kernel_out[i]`` -> the i-th key here even after
    # safetensors' alphabetical load shuffle.
    return {
        "reorder_topk_ids": reorder_topk_ids,
        "src2dst": src2dst,
        "seg_indptr": seg_indptr,
    }
