"""Oracle reference for L1_07_dequantize_k_cache_fast_kernel.

Tier: formula_exact_manual
Tolerance class: elementwise_exact_or_inf_safe
Category: quantization

Generated by scripts/phase_b_oracle.py. The kernel under test is the
GPU triton implementation vendored in kernel.py; this file authors an
eager PyTorch reference from the operation's documented mathematical
definition (no upstream code copy).

Upstream contract (SGLang ``_dequantize_k_cache_fast``,
``sglang/srt/layers/attention/nsa/dequant_k_cache.py``): the input is a
single PACKED fp8 K cache row ``quant_k_cache[num_tokens, 656]`` of
dtype ``float8_e4m3fn``. Its 656 byte-lanes are unpacked by slice +
byte reinterpret exactly as the frozen wrapper does:

    nope_q = quant_k_cache[:, :512]                     # fp8 [B, 512]
    nope_s = quant_k_cache[:, 512:528].view(float32)    # [B, 4] scales
    rope   = quant_k_cache[:, 528:656].view(bfloat16)   # [B, 64] passthrough

The nope half is per-128-group dequantised
(``out[:, j] = nope_q[:, j].float() * nope_s[:, j // 128]``) and cast to
bf16; the rope half is a straight passthrough. The result is
``output[B, 576]`` bf16 == concat(dequant_nope[B, 512], rope[B, 64]).
"""
from __future__ import annotations

import torch

# Frozen upstream constants (kernel.py ``_dequantize_k_cache_fast``).
_DIM_QUANT = 656
_DIM_NOPE = 512
_DIM_ROPE = 64
_GROUP_SIZE = 128
_NUM_TILES = _DIM_NOPE // _GROUP_SIZE  # 4


def _dequantize_k_cache_fast(quant_k_cache: torch.Tensor) -> torch.Tensor:
    """Independent PyTorch reproduction of the frozen triton kernel.

    Reproduces the exact unpack + per-group dequant + rope passthrough of
    SGLang ``_dequantize_k_cache_fast``. Never calls the kernel.

    quant_k_cache: ``[num_tokens, 656]`` fp8 (``float8_e4m3fn``).
    Returns ``[num_tokens, 576]`` bf16.
    """
    assert quant_k_cache.dtype == torch.float8_e4m3fn, (
        f"quant_k_cache must be float8_e4m3fn, got {quant_k_cache.dtype}"
    )
    num_tokens, dim_quant = quant_k_cache.shape
    assert dim_quant == _DIM_QUANT, f"dim_quant {dim_quant} != {_DIM_QUANT}"

    # Byte-reinterpret unpack -- identical to the frozen wrapper's slicing.
    input_nope_q = quant_k_cache[:, :_DIM_NOPE]
    input_nope_s = quant_k_cache[
        :, _DIM_NOPE : _DIM_NOPE + _NUM_TILES * 4
    ].view(torch.float32)
    input_rope = quant_k_cache[:, _DIM_NOPE + _NUM_TILES * 4 :].view(
        torch.bfloat16
    )

    # Per-128-group dequant: out[:, j] = nope_q[:, j].float() * nope_s[:, j//128].
    qv = input_nope_q.to(torch.float32).reshape(
        num_tokens, _NUM_TILES, _GROUP_SIZE
    )
    sv = input_nope_s.to(torch.float32).reshape(num_tokens, _NUM_TILES, 1)
    # fp32 product then round-to-nearest-even cast to bf16 -- byte-identical to
    # the kernel's `(y_q * y_s).to(output.dtype.element_ty)` on a real device.
    # The CPU TRITON_INTERPRET=1 cast truncates instead of RNE (a tooling
    # artifact), so the anchor is GPU-re-confirmed; on the device the fp32
    # product and RNE bf16 cast are identical to the kernel's, so the output is
    # bit-exact -- hence the exact tolerance (garbage byte-reinterpreted scales
    # may produce inf/nan, which must match position-for-position).
    dequant_nope = (qv * sv).reshape(num_tokens, _DIM_NOPE).to(torch.bfloat16)

    # rope half is a straight bf16 passthrough.
    return torch.cat([dequant_nope, input_rope.to(torch.bfloat16)], dim=-1)


def run(inputs: dict) -> dict:
    return {"output": _dequantize_k_cache_fast(inputs["quant_k_cache"])}
