from __future__ import annotations

import torch
import torch.nn.functional as F


def _state_passing_fwd(
    states: torch.Tensor, dA_cumsum: torch.Tensor,
    initial_states: torch.Tensor | None,
) -> torch.Tensor:
    """Mamba2 inter-chunk state passing recurrence:
    S_c = exp(dA_chunk_total_c) · S_{c-1} + states_c.
    states: [n_chunks, ...]; dA_cumsum: [n_chunks] chunk-final decay.
    """
    sf = states.to(torch.float32)
    nC = sf.shape[0]
    decay = torch.exp(dA_cumsum.to(torch.float32))
    out = torch.zeros_like(sf)
    prev = (initial_states.to(torch.float32)
            if initial_states is not None else torch.zeros_like(sf[0]))
    for c in range(nC):
        cur = decay[c].reshape((-1,) + (1,) * (sf.dim() - 1))[0] * prev + sf[c]
        out[c] = cur
        prev = cur
    return out.to(states.dtype)


